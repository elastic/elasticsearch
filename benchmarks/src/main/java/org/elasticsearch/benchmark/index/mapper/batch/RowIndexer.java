package org.elasticsearch.benchmark.index.mapper.batch;

import org.apache.lucene.index.IndexWriter;
import org.elasticsearch.action.index.IndexRequest;
import org.elasticsearch.benchmark.index.mapper.batch.IndexingFixture.RequestBatch;
import org.elasticsearch.benchmark.index.mapper.batch.LuceneSink.SeqNoStamper;
import org.elasticsearch.index.engine.Engine;
import org.elasticsearch.index.mapper.BytesSource;
import org.elasticsearch.index.mapper.DocumentSource;
import org.elasticsearch.index.mapper.MapperService;
import org.elasticsearch.index.mapper.ParsedDocument;
import org.elasticsearch.index.mapper.RowSource;
import org.elasticsearch.index.mapper.SourceToParse;
import org.elasticsearch.index.shard.IndexShard;
import org.elasticsearch.plugins.internal.XContentMeteringParserDecorator;
import org.elasticsearch.sourcebatch.SourceRowXContentParser;

import java.io.IOException;
import java.util.Map;

/**
 * The row path without the engine: {@code IndexShard.prepareIndex} then {@code addDocuments}, one document at a time.
 * {@link RowSourceKind#BATCH_ROW} reads each document from the batch row and is the real production fallback when a batch
 * cannot go columnar; {@link RowSourceKind#JSON} parses the original JSON bytes and is the classic bulk reference.
 */
public final class RowIndexer {

    public enum RowSourceKind {
        BATCH_ROW,
        JSON
    }

    private final MapperService mapperService;
    private final RowSourceKind kind;

    public RowIndexer(MapperService mapperService, RowSourceKind kind) {
        this.mapperService = mapperService;
        this.kind = kind;
    }

    public int index(IndexWriter writer, SeqNoStamper stamper, RequestBatch[] requests) throws IOException {
        int docs = 0;
        for (RequestBatch request : requests) {
            docs += indexRequest(writer, stamper, request);
        }
        return docs;
    }

    public int indexRequest(IndexWriter writer, SeqNoStamper stamper, RequestBatch request) throws IOException {
        SourceRowXContentParser.SchemaNode schemaTree = kind == RowSourceKind.BATCH_ROW
            ? SourceRowXContentParser.buildSchemaTree(request.batch().schema())
            : null;
        long relativeTimeInNanos = System.nanoTime();
        int size = request.size();
        for (int i = 0; i < size; i++) {
            IndexRequest indexRequest = (IndexRequest) request.items()[i].request();
            DocumentSource source = switch (kind) {
                case BATCH_ROW -> new RowSource(
                    schemaTree,
                    request.batch().row(indexRequest.indexSource().rowIndex()),
                    indexRequest.getContentType()
                );
                case JSON -> new BytesSource(request.json()[i], indexRequest.getContentType(), indexRequest.getIncludeSourceOnError());
            };
            SourceToParse sourceToParse = new SourceToParse(
                indexRequest.id(),
                source,
                indexRequest.routing(),
                Map.of(),
                Map.of(),
                XContentMeteringParserDecorator.NOOP,
                indexRequest.tsid()
            );
            Engine.Index op = IndexShard.prepareIndex(
                mapperService,
                sourceToParse,
                stamper.nextSeqNo(),
                stamper.primaryTerm(),
                stamper.version(),
                indexRequest.versionType(),
                Engine.Operation.Origin.PRIMARY,
                indexRequest.getAutoGeneratedTimestamp(),
                indexRequest.isRetry(),
                indexRequest.ifSeqNo(),
                indexRequest.ifPrimaryTerm(),
                relativeTimeInNanos
            );
            ParsedDocument parsed = op.parsedDoc();
            parsed.updateSeqID(op.seqNo(), op.primaryTerm());
            parsed.version().setLongValue(op.version());
            writer.addDocuments(op.docs());
        }
        return size;
    }
}

package org.elasticsearch.gradle.internal.antlr;

import org.gradle.api.DefaultTask;
import org.gradle.api.GradleException;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.provider.ListProperty;
import org.gradle.api.tasks.Input;
import org.gradle.api.tasks.Internal;
import org.gradle.api.tasks.TaskAction;
import org.gradle.api.tasks.UntrackedTask;

import java.io.IOException;
import java.io.Serializable;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.FileSystems;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.PathMatcher;
import java.nio.file.StandardCopyOption;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Post-processes the Java sources and token files generated by ANTLR so they can be checked in.
 *
 * <p>The task runs these steps in order:
 * <ol>
 *     <li>moves the {@link #getTokenFiles() token files} from the {@link #getGeneratedSourcesDir() generated sources
 *     directory} to the {@link #getTokensDir() tokens directory} (usually the grammar directory, for use in IDEs)</li>
 *     <li>applies the {@link #getEdits() regular expression edits} in declaration order</li>
 *     <li>normalizes line endings to {@code \n} and makes sure files end with a line break, for the files matched by
 *     {@link #getLineEndingIncludes()}</li>
 * </ol>
 *
 * <p>Includes are glob patterns matched against file names in the generated sources directory (not recursive).
 * Patterns and replacements use {@link java.util.regex.Pattern} / {@link Matcher#replaceAll(String)} syntax, so groups
 * are referenced as {@code $1}. Each pattern is applied to the whole file content.
 *
 * <p>This replaces the Ant {@code move}, {@code replaceregexp} and {@code fixcrlf} tasks the regen tasks used before.
 * Like {@code replaceregexp}, {@link #replaceFirst} only replaces the first match in each file.
 */
@UntrackedTask(because = "Rewrites generated sources in place")
public abstract class PostProcessAntlrSourcesTask extends DefaultTask {

    /**
     * A regular expression edit applied to all files matching {@code include}.
     */
    public record SourceEdit(String include, String pattern, String replacement, boolean global) implements Serializable {}

    public PostProcessAntlrSourcesTask() {
        setGroup("build");
        setDescription("Post-processes ANTLR generated sources");
    }

    @Internal
    public abstract DirectoryProperty getGeneratedSourcesDir();

    @Internal
    public abstract DirectoryProperty getTokensDir();

    /**
     * Names of the token files to move from the generated sources directory to the tokens directory.
     */
    @Input
    public abstract ListProperty<String> getTokenFiles();

    @Input
    public abstract ListProperty<SourceEdit> getEdits();

    @Input
    public abstract ListProperty<String> getLineEndingIncludes();

    /**
     * Replaces the first match of {@code pattern} in each file matching {@code include}.
     */
    public void replaceFirst(String include, String pattern, String replacement) {
        getEdits().add(new SourceEdit(include, pattern, replacement, false));
    }

    /**
     * Replaces all matches of {@code pattern} in each file matching {@code include}.
     */
    public void replaceAll(String include, String pattern, String replacement) {
        getEdits().add(new SourceEdit(include, pattern, replacement, true));
    }

    /**
     * Normalizes line endings of all files matching {@code include} after all edits have been applied.
     */
    public void fixLineEndings(String include) {
        getLineEndingIncludes().add(include);
    }

    @TaskAction
    public void postProcess() throws IOException {
        Path sourcesDir = getGeneratedSourcesDir().get().getAsFile().toPath();
        moveTokenFiles(sourcesDir);
        for (SourceEdit edit : getEdits().get()) {
            Pattern pattern = Pattern.compile(edit.pattern());
            forEachMatchingFile(sourcesDir, edit.include(), content -> applyEdit(content, pattern, edit.replacement(), edit.global()));
        }
        for (String include : getLineEndingIncludes().get()) {
            forEachMatchingFile(sourcesDir, include, PostProcessAntlrSourcesTask::normalizeLineEndings);
        }
    }

    private void moveTokenFiles(Path sourcesDir) throws IOException {
        List<String> tokenFiles = getTokenFiles().get();
        if (tokenFiles.isEmpty()) {
            return;
        }
        Path tokensDir = getTokensDir().get().getAsFile().toPath();
        Files.createDirectories(tokensDir);
        for (String tokenFile : tokenFiles) {
            Path source = sourcesDir.resolve(tokenFile);
            if (Files.exists(source) == false) {
                throw new GradleException("Expected ANTLR token file " + source + " does not exist");
            }
            Files.move(source, tokensDir.resolve(tokenFile), StandardCopyOption.REPLACE_EXISTING);
        }
    }

    private static void forEachMatchingFile(Path dir, String include, java.util.function.UnaryOperator<String> transformation)
        throws IOException {
        PathMatcher matcher = FileSystems.getDefault().getPathMatcher("glob:" + include);
        List<Path> files;
        try (Stream<Path> stream = Files.list(dir)) {
            files = stream.filter(Files::isRegularFile).filter(p -> matcher.matches(p.getFileName())).sorted().toList();
        }
        if (files.isEmpty()) {
            throw new GradleException("No files in " + dir + " match '" + include + "'");
        }
        for (Path file : files) {
            try {
                String content = Files.readString(file, StandardCharsets.UTF_8);
                String transformed = transformation.apply(content);
                if (transformed.equals(content) == false) {
                    Files.writeString(file, transformed, StandardCharsets.UTF_8);
                }
            } catch (IOException e) {
                throw new UncheckedIOException("Failed to post-process " + file, e);
            }
        }
    }

    static String applyEdit(String content, Pattern pattern, String replacement, boolean global) {
        Matcher matcher = pattern.matcher(content);
        return global ? matcher.replaceAll(replacement) : matcher.replaceFirst(replacement);
    }

    /**
     * Converts {@code \r\n} and lone {@code \r} to {@code \n} and appends a final line break if missing,
     * matching Ant's {@code fixcrlf eol="lf"} defaults.
     */
    static String normalizeLineEndings(String content) {
        String normalized = content.replace("\r\n", "\n").replace('\r', '\n');
        if (normalized.isEmpty() == false && normalized.endsWith("\n") == false) {
            normalized = normalized + "\n";
        }
        return normalized;
    }
}

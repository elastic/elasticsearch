package org.elasticsearch.gradle.internal.ospackage.deb;

import org.elasticsearch.gradle.internal.ospackage.Dependency;
import org.elasticsearch.gradle.internal.ospackage.PackageWriter;
import org.gradle.api.GradleException;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.vafer.jdeb.Compression;
import org.vafer.jdeb.Console;
import org.vafer.jdeb.DataProducer;
import org.vafer.jdeb.DebMaker;
import org.vafer.jdeb.producers.DataProducerLink;

import java.io.File;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.text.SimpleDateFormat;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.Date;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Stream;

/**
 * Writes a deb archive using the jdeb library. Control files (control, conffiles) and maintainer
 * scripts are generated by {@link MaintainerScriptsGenerator} into a task-private debian directory.
 */
class DebPackageWriter implements PackageWriter {

    private static final Logger logger = LoggerFactory.getLogger(DebPackageWriter.class);

    private final Deb task;
    private final File debianDir;
    private final List<DataProducer> dataProducers = new ArrayList<>();
    private final List<InstallDir> installDirs = new ArrayList<>();

    record InstallDir(String name, String user, String group, int mode) {}

    DebPackageWriter(Deb task, File debianDir) throws IOException {
        this.task = task;
        this.debianDir = debianDir;
        if (Files.exists(debianDir.toPath())) {
            try (Stream<Path> paths = Files.walk(debianDir.toPath())) {
                paths.sorted(Comparator.reverseOrder()).forEach(path -> {
                    try {
                        Files.delete(path);
                    } catch (IOException e) {
                        throw new UncheckedIOException(e);
                    }
                });
            }
        }
        Files.createDirectories(debianDir.toPath());
    }

    @Override
    public void addFile(String path, File source, int mode, String user, String group, int fileTypeFlags) {
        logger.debug("adding file {}", path);
        dataProducers.add(new DataProducers.FileProducer(path, source, user, 0, group, 0, mode));
    }

    @Override
    public void addDirectory(String path, int mode, String user, String group) {
        logger.debug("adding directory {}", path);
        dataProducers.add(new DataProducers.DirProducer(path, user, 0, group, 0, mode));
        // parent directories are created implicitly by jdeb, so install them explicitly in postinst
        installDirs.add(new InstallDir(path, user, group, mode));
    }

    @Override
    public void addLink(String path, String target) {
        logger.debug("adding link {} -> {}", path, target);
        dataProducers.add(new DataProducerLink(path, target, true, null, null, null));
    }

    @Override
    public void finish() throws IOException {
        new MaintainerScriptsGenerator(task, new TemplateHelper(debianDir), debianDir).generate(toContext());

        DebMaker maker = new DebMaker(new GradleLoggerConsole(), dataProducers, null);
        File debFile = task.getArchiveFile().get().getAsFile();
        maker.setControl(debianDir);
        maker.setDeb(debFile);

        String signingKeyId = task.getSigningKeyId().getOrElse("");
        String signingKeyPassphrase = task.getSigningKeyPassphrase().getOrElse("");
        File signingKeyRingFile = task.getSigningKeyRingFile().isPresent() ? task.getSigningKeyRingFile().get().getAsFile() : null;
        if (signingKeyId.isBlank() == false
            && signingKeyPassphrase.isBlank() == false
            && signingKeyRingFile != null
            && signingKeyRingFile.exists()) {
            maker.setKey(signingKeyId);
            maker.setPassphrase(signingKeyPassphrase);
            maker.setKeyring(signingKeyRingFile);
            maker.setSignPackage(true);
        }

        try {
            logger.info("creating debian package: {}", debFile);
            maker.setCompression(Compression.GZIP.toString());
            maker.makeDeb();
        } catch (Exception e) {
            throw new GradleException("Can't build debian package " + debFile, e);
        }
        logger.info("created deb {}", debFile);
    }

    private static class GradleLoggerConsole implements Console {
        @Override
        public void debug(String message) {
            logger.debug(message);
        }

        @Override
        public void info(String message) {
            logger.info(message);
        }

        @Override
        public void warn(String message) {
            logger.warn(message);
        }
    }

    /**
     * Assembles the context consumed by the debian control and maintainer script templates. Keys
     * without a corresponding task property are fixed to the values the Elasticsearch packages
     * have always used.
     */
    private Map<String, Object> toContext() {
        Map<String, Object> context = new LinkedHashMap<>();
        context.put("name", task.getPackageName().get());
        context.put("maintainer", task.getMaintainer().getOrElse(""));
        context.put("uploaders", "");
        context.put("priority", "optional");
        context.put("description", task.getPackageDescription().getOrElse(""));
        context.put("distribution", task.getDistribution().getOrElse(""));
        context.put("summary", task.getSummary().getOrElse(""));
        context.put("section", task.getPackageGroup().getOrNull());
        context.put("time", new SimpleDateFormat("EEE, dd MMM yyyy HH:mm:ss Z", Locale.ROOT).format(new Date()));
        context.put("provides", "");
        context.put("depends", joinDependencies(task.getDependencies().getOrElse(List.of())));
        context.put("url", task.getUrl().getOrElse(""));
        context.put("arch", task.getArchString());
        context.put("multiArch", "");
        context.put("conflicts", joinDependencies(task.getConflicts().getOrElse(List.of())));
        context.put("recommends", "");
        context.put("suggests", "");
        context.put("enhances", "");
        context.put("preDepends", "");
        context.put("breaks", "");
        context.put("replaces", "");
        context.put("fullVersion", buildFullVersion());
        // in the deb control file, header XB-Foo becomes Foo in the binary package
        Map<String, String> customFields = new LinkedHashMap<>();
        task.getCustomFields().getOrElse(Map.of()).forEach((key, value) -> customFields.put("XB-" + capitalize(key), value));
        context.put("customFields", customFields);
        context.put("dirs", installDirs.stream().map(dir -> Map.of("install", MaintainerScriptsGenerator.installLine(dir))).toList());
        return context;
    }

    private static String joinDependencies(List<Dependency> dependencies) {
        return String.join(", ", dependencies.stream().map(Dependency::toDebString).toList());
    }

    private static String capitalize(String value) {
        return value.isEmpty() ? value : Character.toUpperCase(value.charAt(0)) + value.substring(1);
    }

    private String buildFullVersion() {
        StringBuilder fullVersion = new StringBuilder(task.getVersion().get());
        String release = task.getRelease().getOrNull();
        if (release != null && release.isEmpty() == false) {
            fullVersion.append('-').append(release);
        }
        return fullVersion.toString();
    }
}

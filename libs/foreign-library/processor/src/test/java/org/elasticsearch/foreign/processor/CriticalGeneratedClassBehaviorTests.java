package org.elasticsearch.foreign.processor;

import java.lang.foreign.Arena;
import java.lang.foreign.MemorySegment;

/**
 * Behavioral tests for {@code @Critical} bindings generated by {@link ImplClassWriter}. These tests
 * load the generated implementation through the {@code LibraryProvider} SPI (via {@link #loadLibrary})
 * and actually invoke the method against libc's {@code memcmp}, testing the downcall wiring end to end.
 * {@code memcmp} is chosen as it requires no native library build dependency, works on any platform,
 * and it is pure/read-only.
 */
public class CriticalGeneratedClassBehaviorTests extends ProcessorTestCase {

    private static final String MEMCMP_LIB = """
        package test;
        import java.lang.foreign.MemorySegment;
        import org.elasticsearch.foreign.LibrarySpecification;
        import org.elasticsearch.foreign.Function;
        import org.elasticsearch.foreign.Critical;
        @LibrarySpecification
        public interface MemCmpLib {
            @Function("memcmp")
            @Critical
            int memcmp(MemorySegment a, MemorySegment b, long n);
        }
        """;

    /**
     * A {@code @Critical} binding links and calls {@code memcmp} correctly with off-heap segments.
     */
    public void testCriticalCallOffHeapSegments() throws Throwable {
        LoadedLibrary lib = loadLibrary("test.MemCmpLib", MEMCMP_LIB);
        try (Arena arena = Arena.ofConfined()) {
            MemorySegment a = fill(arena.allocate(4));
            MemorySegment b = fill(arena.allocate(4));
            assertEquals("equal 4-byte segments compare equal", 0, (int) lib.call("memcmp", a, b, 4L));
        }
    }

    /**
     * The generated downcall is wired with {@code Linker.Option.critical(true)}, so it accepts heap-backed
     * {@link MemorySegment}s directly. Passing on-heap segments links and calls {@code memcmp} correctly.
     */
    public void testCriticalCallHeapSegments() throws Throwable {
        LoadedLibrary lib = loadLibrary("test.MemCmpLib", MEMCMP_LIB);
        MemorySegment a = MemorySegment.ofArray(new byte[] { 0, 1, 2, 3 });
        MemorySegment b = MemorySegment.ofArray(new byte[] { 0, 1, 2, 3 });
        assertEquals("equal 4-byte heap segments compare equal", 0, (int) lib.call("memcmp", a, b, 4L));
    }

    public void testNonCriticalBindingRequiresNativeSegment() throws Throwable {
        ProcessorTestCase.LoadedLibrary lib = loadLibrary("test.MemCmpLib", """
            package test;
            import java.lang.foreign.MemorySegment;
            import org.elasticsearch.foreign.Function;
            import org.elasticsearch.foreign.LibrarySpecification;
            @LibrarySpecification
            public interface MemCmpLib {
                @Function("memcmp")
                int memcmp(MemorySegment a, MemorySegment b, long n);
            }
            """);

        try (Arena arena = Arena.ofConfined()) {
            MemorySegment nativeSegment = fill(arena.allocate(8));
            MemorySegment other = fill(arena.allocate(8));
            assertEquals(0, (int) lib.call("memcmp", nativeSegment, other, 8L));

            MemorySegment heapSegment = MemorySegment.ofArray(new byte[8]);
            AssertionError e = lib.expectThrows(AssertionError.class, "memcmp", heapSegment, other, 8L);
            assertEquals("non-critical bindings require native memory segments", e.getMessage());
        }
    }
}

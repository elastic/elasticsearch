package org.elasticsearch.foreign.processor;

import java.lang.foreign.Arena;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.ValueLayout;
import java.nio.charset.StandardCharsets;

/**
 * Behavioral tests for {@code @RawAddress} bindings generated by {@link ImplClassWriter}. These tests
 * load the generated implementation through the {@code LibraryProvider} SPI (via {@link #loadLibrary})
 * and actually invoke the method against libc's {@code memcmp}, testing the downcall wiring end to end.
 * {@code memcmp} is chosen as it requires no native library build dependency, works on any platform,
 * and it is pure/read-only.
 */
public class RawAddressGeneratedClassBehaviorTests extends ProcessorTestCase {
    private static final String RAW_SEGMENT_MEMCMP_LIB = """
        package test;
        import java.lang.foreign.MemorySegment;
        import org.elasticsearch.foreign.Function;
        import org.elasticsearch.foreign.LibrarySpecification;
        import org.elasticsearch.foreign.RawAddress;
        import org.elasticsearch.foreign.VectorSegment;
        @LibrarySpecification
        public interface MemCmpLib {
            @Function("memcmp")
            int memcmp(
                @RawAddress @VectorSegment(countParam = "n", elementBits = 8) MemorySegment a,
                @VectorSegment(countParam = "n", elementBits = 8) MemorySegment b,
                long n);
        }
        """;

    public void testRawAddressRequiresNativeSegment() throws Throwable {
        ProcessorTestCase.LoadedLibrary lib = loadLibrary("test.MemCmpLib", RAW_SEGMENT_MEMCMP_LIB);

        try (Arena arena = Arena.ofConfined()) {
            MemorySegment nativeSegment = fill(arena.allocate(8));
            MemorySegment other = fill(arena.allocate(8));
            assertEquals(0, (int) lib.call("memcmp", nativeSegment, other, 8L));

            MemorySegment heapSegment = MemorySegment.ofArray(new byte[8]);
            AssertionError e = lib.expectThrows(AssertionError.class, "memcmp", heapSegment, other, 8L);
            assertEquals("raw address requires a native memory segment", e.getMessage());
        }
    }

    public void testRawAddressRequiresLiveSegment() throws Throwable {
        ProcessorTestCase.LoadedLibrary lib = loadLibrary("test.MemCmpLib", RAW_SEGMENT_MEMCMP_LIB);

        Arena closedArena = Arena.ofConfined();
        MemorySegment closedSegment = closedArena.allocate(8);
        closedArena.close();
        try (Arena arena = Arena.ofConfined()) {
            AssertionError e = lib.expectThrows(AssertionError.class, "memcmp", closedSegment, arena.allocate(8), 8L);
            assertTrue(e.getCause() instanceof AssertionError);
            assertEquals("raw address requires a live memory segment", e.getCause().getMessage());
        }
    }

    public void testRawAddressWorksWithStringParameter() throws Throwable {
        ProcessorTestCase.LoadedLibrary lib = loadLibrary("test.MemCmpLib", """
            package test;
            import java.lang.foreign.MemorySegment;
            import org.elasticsearch.foreign.Function;
            import org.elasticsearch.foreign.LibrarySpecification;
            import org.elasticsearch.foreign.RawAddress;
            @LibrarySpecification
            public interface MemCmpLib {
                @Function("memcmp")
                int memcmp(@RawAddress MemorySegment a, String b, long n);
            }
            """);

        try (Arena arena = Arena.ofConfined()) {
            String s = "ABC";
            byte[] stringBytes = s.getBytes(StandardCharsets.UTF_8);
            MemorySegment nativeSegment = arena.allocate(stringBytes.length);
            MemorySegment.copy(stringBytes, 0, nativeSegment, ValueLayout.JAVA_BYTE, 0L, stringBytes.length);
            assertEquals(0, (int) lib.call("memcmp", nativeSegment, s, stringBytes.length));
        }
    }
}

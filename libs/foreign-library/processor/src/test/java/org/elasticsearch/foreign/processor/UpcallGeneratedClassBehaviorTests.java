package org.elasticsearch.foreign.processor;

import org.elasticsearch.core.SuppressForbidden;

import java.lang.foreign.Arena;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.ValueLayout;
import java.lang.reflect.Constructor;
import java.lang.reflect.Method;
import java.util.LinkedHashMap;
import java.util.Locale;
import java.util.Map;

/**
 * Behavioral test for {@code @Upcall} bindings generated by {@link ImplClassWriter}: unlike
 * {@link ImplClassWriterTests#testUpcallParamGeneratesStubCall}, which only asserts the generated
 * class shape via {@code loadClassNoInit}, this test instantiates the generated class, drives a real
 * {@code Arena}-scoped upcall stub through libc's {@code qsort}, and proves native code calling back
 * into the JVM through the generated stub actually works end to end.
 *
 * <p>{@code qsort} is chosen because it is a real, ubiquitous POSIX callback API available via the
 * default linker lookup on every POSIX platform, requiring no native library build dependency.
 */
@SuppressForbidden(
    reason = "tests instantiate package-private processor-generated classes and invoke their public methods "
        + "cross-package; getDeclaredConstructor/setAccessible is the only way to do that via reflection"
)
public class UpcallGeneratedClassBehaviorTests extends ProcessorTestCase {

    /**
     * qsort's comparator symbol is resolved via the CRT on Windows rather than the default linker
     * lookup, so this test (which relies on the POSIX {@code qsort} being reachable through
     * {@code Linker.nativeLinker().defaultLookup()}) is skipped there.
     */
    public void testQsortUpcallSortsArray() throws Exception {
        if (System.getProperty("os.name", "").toLowerCase(Locale.ROOT).startsWith("windows")) {
            return;
        }

        Map<String, String> sources = new LinkedHashMap<>();
        sources.put("test.IntCompare", """
            package test;
            import java.lang.foreign.MemorySegment;
            import org.elasticsearch.foreign.Upcall;
            @Upcall
            @FunctionalInterface
            public interface IntCompare {
                int compare(MemorySegment a, MemorySegment b);
            }
            """);
        sources.put("test.AscendingIntCompare", """
            package test;
            import java.lang.foreign.MemorySegment;
            import java.lang.foreign.ValueLayout;
            public final class AscendingIntCompare implements IntCompare {
                public int compare(MemorySegment a, MemorySegment b) {
                    // qsort passes raw element pointers as zero-length MemorySegments; widen before reading.
                    int x = a.reinterpret(ValueLayout.JAVA_INT.byteSize()).get(ValueLayout.JAVA_INT, 0);
                    int y = b.reinterpret(ValueLayout.JAVA_INT.byteSize()).get(ValueLayout.JAVA_INT, 0);
                    return Integer.compare(x, y);
                }
            }
            """);
        sources.put("test.QsortLib", """
            package test;
            import java.lang.foreign.MemorySegment;
            import org.elasticsearch.foreign.LibrarySpecification;
            import org.elasticsearch.foreign.Function;
            @LibrarySpecification
            public interface QsortLib {
                @Function("qsort")
                void qsort(MemorySegment base, long nmemb, long size, IntCompare compar);
            }
            """);

        CompilationResult result = compile(sources);
        assertTrue("Expected compilation to succeed but got errors: " + result.errors(), result.success());

        Class<?> implClass = result.loadClass("test.QsortLib$Impl");
        // Load through implClass's own classloader (not another loadClass() call, which would spin up a
        // separate URLClassLoader) so the Class objects are comparable for reflective method lookup.
        Class<?> intCompareClass = Class.forName("test.IntCompare", false, implClass.getClassLoader());
        Class<?> ascendingClass = Class.forName("test.AscendingIntCompare", true, implClass.getClassLoader());

        Constructor<?> ctor = implClass.getDeclaredConstructor();
        ctor.setAccessible(true);
        Object instance = ctor.newInstance();

        Method qsort = implClass.getMethod("qsort", MemorySegment.class, long.class, long.class, intCompareClass);
        qsort.setAccessible(true);
        Object comparator = ascendingClass.getDeclaredConstructor().newInstance();

        int[] unsorted = { 5, 3, 4, 1, 2 };
        try (Arena arena = Arena.ofConfined()) {
            MemorySegment base = arena.allocate((long) unsorted.length * Integer.BYTES, Integer.BYTES);
            for (int i = 0; i < unsorted.length; i++) {
                base.setAtIndex(ValueLayout.JAVA_INT, i, unsorted[i]);
            }

            qsort.invoke(instance, base, (long) unsorted.length, (long) Integer.BYTES, comparator);

            int[] sorted = new int[unsorted.length];
            for (int i = 0; i < sorted.length; i++) {
                sorted[i] = base.getAtIndex(ValueLayout.JAVA_INT, i);
            }
            assertEquals("qsort must sort ascending via the upcall comparator", "[1, 2, 3, 4, 5]", java.util.Arrays.toString(sorted));
        }
    }
}

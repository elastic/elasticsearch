package org.elasticsearch.index.engine;

import org.apache.lucene.search.similarities.BM25Similarity;
import org.elasticsearch.core.Nullable;
import org.elasticsearch.index.cache.query.TrivialQueryCachingPolicy;
import org.elasticsearch.index.mapper.DocumentParser;
import org.elasticsearch.index.mapper.MappingLookup;
import org.elasticsearch.index.mapper.ObjectMapper;
import org.elasticsearch.index.shard.ShardId;
import org.elasticsearch.index.translog.Translog;

import java.io.IOException;
import java.util.Arrays;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.stream.Stream;

/**
 *
 * A utility class to assert that translog operations with the same sequence number
 * in the same generation are either identical or equivalent when synthetic sources are used.
 */
public abstract class TranslogOperationAsserter {
    public static final TranslogOperationAsserter DEFAULT = new TranslogOperationAsserter() {};

    private TranslogOperationAsserter() {

    }

    public static TranslogOperationAsserter withEngineConfig(EngineConfig engineConfig) {
        return new TranslogOperationAsserter() {
            @Override
            public boolean assertSameIndexOperation(Translog.Index o1, Translog.Index o2) throws IOException {
                if (super.assertSameIndexOperation(o1, o2)) {
                    return true;
                }
                if (engineConfig.getIndexSettings().isRecoverySourceSyntheticEnabled()
                    || engineConfig.getMapperService().mappingLookup().inferenceFields().isEmpty() == false
                    || engineConfig.getMapperService().mappingLookup().syntheticVectorFields().isEmpty() == false) {
                    // for synthetic source and synthetic fields, we check that the resulting source map is equivalent
                    // since ordering might not be preserved.
                    // The original and synthesized source of both operations are compared field by field:
                    // in a mixed cluster the same operation can arrive through replication with its
                    // original source and through recovery with a source partially synthesized by an
                    // older node.
                    if (Translog.Index.equalsWithoutAutoGeneratedTimestampAndSource(o1, o2) == false) {
                        return false;
                    }
                    final SourceStructure structure = SourceStructure.of(engineConfig.getMapperService().mappingLookup());
                    final List<Object> forms1 = forms(structure, engineConfig, o1);
                    final List<Object> forms2 = forms(structure, engineConfig, o2);
                    // Either operation can be the copy that recovery synthesized.
                    return sameFields(structure, null, true, forms1, forms2) || sameFields(structure, null, false, forms1, forms2);
                }
                return false;
            }
        };
    }

    /** Index of the original source in the forms of an operation. The synthesized source follows it. */
    private static final int ORIGINAL = 0;

    /**
     * Returns the two forms of an operation that are compared, its original and its synthesized
     * source, both as returned by {@link #canonical}.
     */
    private static List<Object> forms(SourceStructure structure, EngineConfig engineConfig, Translog.Index op) throws IOException {
        return List.of(
            canonical(structure, null, Translog.Index.sourceAsMap(op)),
            canonical(structure, null, Translog.Index.sourceAsMap(synthesizeSource(engineConfig, op)))
        );
    }

    /**
     * Returns true if every field matches in at least one pairing of a left form with a right form.
     * Fields may need different pairings: in a mixed cluster an older node synthesizes only some vector
     * fields, and re-synthesizing a lossy vector (e.g. a normalized bfloat16) is not idempotent, so no
     * single pairing of whole documents is guaranteed to match.
     *
     * <p>One operation is taken to be the copy that recovery synthesized, and it is the same one for
     * every field. Its original form is what the older node sent, so it is never compared with the
     * synthesized form of the other operation as well. That leaves three pairings: original with
     * original, synthesized with synthesized, and the synthesized form of the other operation with the
     * original form of the recovered one.
     *
     * <p>The mapping decides what a field is. Objects are compared field by field, and arrays of objects
     * element by element when all forms have the same number of elements. Any other value has to match
     * as a whole whatever its shape, because synthesizing can write a field value that is itself an
     * object with other keys, e.g. a GeoJSON point as {@code lat} and {@code lon}.
     *
     * <p>A field that is absent from a form is null there, and null matches only when the field is null
     * in all four forms.
     *
     * @param path the full path of the values being compared, null for the root
     * @param rightIsRecovered whether the right operation, rather than the left, is the recovered copy
     * @param left the forms of the left operation at {@code path}, original first
     * @param right the forms of the right operation at {@code path}, original first
     */
    private static boolean sameFields(
        SourceStructure structure,
        @Nullable String path,
        boolean rightIsRecovered,
        List<Object> left,
        List<Object> right
    ) {
        final List<Object> all = Stream.concat(left.stream(), right.stream()).toList();
        final boolean nullInAllForms = all.stream().allMatch(Objects::isNull);
        for (int l = 0; l < left.size(); l++) {
            for (int r = 0; r < right.size(); r++) {
                // skip the original of the operation that is not the recovered copy against the synthesized form of the one that is
                if (l != r && (l == ORIGINAL) == rightIsRecovered) {
                    continue;
                }
                if (Objects.equals(left.get(l), right.get(r)) && (left.get(l) != null || nullInAllForms)) {
                    return true;
                }
            }
        }
        if (structure.isObject(path) == false) {
            return false;
        }
        if (all.stream().allMatch(v -> v instanceof Map<?, ?>)) {
            final Set<Object> keys = new HashSet<>();
            all.forEach(v -> keys.addAll(((Map<?, ?>) v).keySet()));
            for (Object key : keys) {
                final String childPath = childPath(path, key.toString());
                if (sameFields(structure, childPath, rightIsRecovered, valuesOf(left, key), valuesOf(right, key)) == false) {
                    return false;
                }
            }
            return true;
        }
        final int count = objectCount(all.get(0));
        if (count > 0 && all.stream().allMatch(v -> objectCount(v) == count)) {
            for (int i = 0; i < count; i++) {
                if (sameFields(structure, path, rightIsRecovered, objectsAt(left, i), objectsAt(right, i)) == false) {
                    return false;
                }
            }
            return true;
        }
        return false;
    }

    private static List<Object> valuesOf(List<Object> maps, Object key) {
        // A form without the field contributes null. Arrays.asList, because it accepts null elements.
        return Arrays.asList(maps.stream().map(m -> ((Map<?, ?>) m).get(key)).toArray());
    }

    /** Returns how many objects the value holds: one for an object, the length for an array of objects, otherwise -1. */
    private static int objectCount(Object value) {
        if (value instanceof Map<?, ?>) {
            return 1;
        }
        return value instanceof List<?> list && list.isEmpty() == false && list.stream().allMatch(e -> e instanceof Map<?, ?>)
            ? list.size()
            : -1;
    }

    /** Returns the object at the index in each value, where every value is an object or an array of objects. */
    private static List<Object> objectsAt(List<Object> values, int index) {
        return values.stream().<Object>map(v -> v instanceof List<?> list ? list.get(index) : v).toList();
    }

    private static String childPath(@Nullable String path, String name) {
        return path == null ? name : path + "." + name;
    }

    /**
     * Returns the value with every field under the name the mapping gives it, so that the forms of an
     * operation can be compared field by field. A source can name the field {@code obj.a} as
     * {@code {"obj.a": 1}} or {@code {"obj": {"a": 1}}}, and synthesizing may switch between the two.
     * A dotted name is split where its prefix is an object in the mapping, and the rest of the name is
     * resolved inside that object. The content of a disabled object and the value of any path that is
     * not an object are returned as they are.
     */
    private static Object canonical(SourceStructure structure, @Nullable String path, Object value) {
        if (structure.isObject(path) == false || structure.isDisabled(path)) {
            return value;
        }
        if (value instanceof Map<?, ?> object) {
            final Map<String, Object> fields = new HashMap<>();
            for (Map.Entry<?, ?> entry : object.entrySet()) {
                addField(structure, path, fields, entry.getKey().toString(), entry.getValue());
            }
            return fields;
        }
        if (value instanceof List<?> list && objectCount(list) > 0) {
            return list.stream().map(element -> canonical(structure, path, element)).toList();
        }
        return value;
    }

    private static void addField(SourceStructure structure, @Nullable String path, Map<String, Object> fields, String name, Object value) {
        for (int dot = name.indexOf('.'); dot >= 0; dot = name.indexOf('.', dot + 1)) {
            final String head = name.substring(0, dot);
            final String headPath = childPath(path, head);
            if (structure.isObject(headPath)) {
                final Map<String, Object> child = new HashMap<>();
                child.put(name.substring(dot + 1), value);
                merge(fields, head, canonical(structure, headPath, child));
                return;
            }
        }
        merge(fields, name, canonical(structure, childPath(path, name), value));
    }

    /**
     * Adds a value to an object. A source can give the same path twice, with a dotted name and inside
     * an object: two objects are merged, and any other two values are both kept.
     */
    private static void merge(Map<String, Object> fields, String name, Object value) {
        final Object existing = fields.get(name);
        if (existing == null) {
            fields.put(name, value);
        } else if (existing instanceof Map<?, ?> existingObject && value instanceof Map<?, ?> addedObject) {
            final Map<String, Object> merged = new HashMap<>();
            existingObject.forEach((k, v) -> merged.put(k.toString(), v));
            addedObject.forEach((k, v) -> merge(merged, k.toString(), v));
            fields.put(name, merged);
        } else if (value != null) {
            fields.put(name, Values.of(existing, value));
        }
    }

    /**
     * The values of a path that a source gives more than once, compared without regard to their order.
     */
    private record Values(Map<Object, Integer> counts) {
        static Values of(Object first, Object second) {
            final Map<Object, Integer> counts = new HashMap<>();
            for (Object value : List.of(first, second)) {
                if (value instanceof Values values) {
                    values.counts.forEach((v, count) -> counts.merge(v, count, Integer::sum));
                } else {
                    counts.merge(value, 1, Integer::sum);
                }
            }
            return new Values(counts);
        }
    }

    /**
     * What the mapping says about the paths of a source.
     *
     * @param objectMappers the object mappers of the index by full path
     * @param fields the full paths of the mapped fields
     * @param prefixes every proper dotted prefix of a mapped field or object. A prefix that is not a
     *                 mapper itself comes from a dotted field name under an object without subobjects.
     */
    private record SourceStructure(Map<String, ObjectMapper> objectMappers, Set<String> fields, Set<String> prefixes) {
        static SourceStructure of(MappingLookup mappingLookup) {
            final Set<String> fields = mappingLookup.getFullNameToFieldType().keySet();
            final Set<String> prefixes = new HashSet<>();
            Stream.concat(fields.stream(), mappingLookup.objectMappers().keySet().stream()).forEach(mapped -> {
                for (int dot = mapped.indexOf('.'); dot >= 0; dot = mapped.indexOf('.', dot + 1)) {
                    prefixes.add(mapped.substring(0, dot));
                }
            });
            return new SourceStructure(mappingLookup.objectMappers(), fields, prefixes);
        }

        /**
         * Whether the values at the path hold fields: the root, a mapped object, or a prefix of a mapped
         * path that is not a field itself. A field with multi-fields is a prefix of them and stays a field.
         */
        boolean isObject(@Nullable String path) {
            return path == null || objectMappers.containsKey(path) || (prefixes.contains(path) && fields.contains(path) == false);
        }

        boolean isDisabled(@Nullable String path) {
            final ObjectMapper mapper = path == null ? null : objectMappers.get(path);
            return mapper != null && mapper.isEnabled() == false;
        }
    }

    static Translog.Index synthesizeSource(EngineConfig engineConfig, Translog.Index op) throws IOException {
        final ShardId shardId = engineConfig.getShardId();
        final MappingLookup mappingLookup = engineConfig.getMapperService().mappingLookup();
        final DocumentParser documentParser = engineConfig.getMapperService().documentParser();
        try (var reader = TranslogDirectoryReader.create(shardId, op, mappingLookup, documentParser, engineConfig, () -> {}, true)) {
            final Engine.Searcher searcher = new Engine.Searcher(
                "assert_translog",
                reader,
                new BM25Similarity(),
                null,
                TrivialQueryCachingPolicy.NEVER,
                () -> {}
            );
            try (var snapshot = newSnapshot(engineConfig, op, searcher);) {
                final Translog.Operation normalized = snapshot.next();
                assert normalized != null : "expected one operation; got zero";
                return (Translog.Index) normalized;
            }
        }
    }

    static Translog.Snapshot newSnapshot(EngineConfig engineConfig, Translog.Index op, Engine.Searcher searcher) throws IOException {
        if (engineConfig.getIndexSettings().isRecoverySourceSyntheticEnabled()) {
            return new LuceneSyntheticSourceChangesSnapshot(
                engineConfig.getMapperService(),
                searcher,
                LuceneSyntheticSourceChangesSnapshot.DEFAULT_BATCH_SIZE,
                Integer.MAX_VALUE,
                op.seqNo(),
                op.seqNo(),
                true,
                false
            );
        } else {
            return new LuceneChangesSnapshot(
                engineConfig.getMapperService(),
                searcher,
                LuceneSyntheticSourceChangesSnapshot.DEFAULT_BATCH_SIZE,
                op.seqNo(),
                op.seqNo(),
                true,
                false,
                false
            );
        }
    }

    public boolean assertSameIndexOperation(Translog.Index o1, Translog.Index o2) throws IOException {
        return Translog.Index.equalsWithoutAutoGeneratedTimestamp(o1, o2, true)
            || Translog.Index.equalsWithoutAutoGeneratedTimestamp(o1, o2, false);
    }
}

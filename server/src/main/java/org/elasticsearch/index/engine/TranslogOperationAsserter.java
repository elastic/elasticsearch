package org.elasticsearch.index.engine;

import org.apache.lucene.search.similarities.BM25Similarity;
import org.elasticsearch.index.cache.query.TrivialQueryCachingPolicy;
import org.elasticsearch.index.mapper.DocumentParser;
import org.elasticsearch.index.mapper.MappingLookup;
import org.elasticsearch.index.shard.ShardId;
import org.elasticsearch.index.translog.Translog;

import java.io.IOException;
import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.stream.Stream;

/**
 *
 * A utility class to assert that translog operations with the same sequence number
 * in the same generation are either identical or equivalent when synthetic sources are used.
 */
public abstract class TranslogOperationAsserter {
    public static final TranslogOperationAsserter DEFAULT = new TranslogOperationAsserter() {};

    private TranslogOperationAsserter() {

    }

    public static TranslogOperationAsserter withEngineConfig(EngineConfig engineConfig) {
        return new TranslogOperationAsserter() {
            @Override
            public boolean assertSameIndexOperation(Translog.Index o1, Translog.Index o2) throws IOException {
                if (super.assertSameIndexOperation(o1, o2)) {
                    return true;
                }
                if (engineConfig.getIndexSettings().isRecoverySourceSyntheticEnabled()
                    || engineConfig.getMapperService().mappingLookup().inferenceFields().isEmpty() == false
                    || engineConfig.getMapperService().mappingLookup().syntheticVectorFields().isEmpty() == false) {
                    // for synthetic source and synthetic fields, we check that the resulting source map is equivalent
                    // since ordering might not be preserved.
                    // Synthesize both sides for mixed-cluster scenarios where nodes running different
                    // versions reconstruct source differently. The same operation can arrive through
                    // replication with its original source and through recovery with source partially
                    // reconstructed by an older node.
                    if (Translog.Index.equalsWithoutAutoGeneratedTimestampAndSource(o1, o2) == false) {
                        return false;
                    }
                    final Map<String, Object> synthesized1 = Translog.Index.sourceAsMap(synthesizeSource(engineConfig, o1));
                    final Map<String, Object> synthesized2 = Translog.Index.sourceAsMap(synthesizeSource(engineConfig, o2));
                    return sameFieldsInAnyForm(
                        Arrays.<Object>asList(Translog.Index.sourceAsMap(o1), synthesized1),
                        Arrays.<Object>asList(Translog.Index.sourceAsMap(o2), synthesized2)
                    );
                }
                return false;
            }
        };
    }

    /**
     * Returns true if every field matches in at least one pairing of a left form with a right form, where
     * the forms are the original and synthesized source of each operation. Fields may need different
     * pairings: in a mixed cluster an older node synthesizes only some vector fields, and re-synthesizing
     * a lossy vector (e.g. a normalized bfloat16) is not idempotent, so no single pairing of whole
     * documents is guaranteed to match. Objects are compared field by field; any other value, including
     * arrays, has to match as a whole.
     */
    private static boolean sameFieldsInAnyForm(List<Object> left, List<Object> right) {
        for (Object l : left) {
            for (Object r : right) {
                if (Objects.equals(l, r)) {
                    return true;
                }
            }
        }
        if (Stream.concat(left.stream(), right.stream()).allMatch(v -> v instanceof Map) == false) {
            return false;
        }
        final Set<Object> keys = new HashSet<>();
        Stream.concat(left.stream(), right.stream()).forEach(v -> keys.addAll(((Map<?, ?>) v).keySet()));
        for (Object key : keys) {
            if (sameFieldsInAnyForm(valuesOf(left, key), valuesOf(right, key)) == false) {
                return false;
            }
        }
        return true;
    }

    private static List<Object> valuesOf(List<Object> maps, Object key) {
        // Arrays.asList, since a field may be missing or null in some of the forms
        return Arrays.asList(maps.stream().map(m -> ((Map<?, ?>) m).get(key)).toArray());
    }

    static Translog.Index synthesizeSource(EngineConfig engineConfig, Translog.Index op) throws IOException {
        final ShardId shardId = engineConfig.getShardId();
        final MappingLookup mappingLookup = engineConfig.getMapperService().mappingLookup();
        final DocumentParser documentParser = engineConfig.getMapperService().documentParser();
        try (var reader = TranslogDirectoryReader.create(shardId, op, mappingLookup, documentParser, engineConfig, () -> {}, true)) {
            final Engine.Searcher searcher = new Engine.Searcher(
                "assert_translog",
                reader,
                new BM25Similarity(),
                null,
                TrivialQueryCachingPolicy.NEVER,
                () -> {}
            );
            try (var snapshot = newSnapshot(engineConfig, op, searcher);) {
                final Translog.Operation normalized = snapshot.next();
                assert normalized != null : "expected one operation; got zero";
                return (Translog.Index) normalized;
            }
        }
    }

    static Translog.Snapshot newSnapshot(EngineConfig engineConfig, Translog.Index op, Engine.Searcher searcher) throws IOException {
        if (engineConfig.getIndexSettings().isRecoverySourceSyntheticEnabled()) {
            return new LuceneSyntheticSourceChangesSnapshot(
                engineConfig.getMapperService(),
                searcher,
                LuceneSyntheticSourceChangesSnapshot.DEFAULT_BATCH_SIZE,
                Integer.MAX_VALUE,
                op.seqNo(),
                op.seqNo(),
                true,
                false
            );
        } else {
            return new LuceneChangesSnapshot(
                engineConfig.getMapperService(),
                searcher,
                LuceneSyntheticSourceChangesSnapshot.DEFAULT_BATCH_SIZE,
                op.seqNo(),
                op.seqNo(),
                true,
                false,
                false
            );
        }
    }

    public boolean assertSameIndexOperation(Translog.Index o1, Translog.Index o2) throws IOException {
        return Translog.Index.equalsWithoutAutoGeneratedTimestamp(o1, o2, true)
            || Translog.Index.equalsWithoutAutoGeneratedTimestamp(o1, o2, false);
    }
}

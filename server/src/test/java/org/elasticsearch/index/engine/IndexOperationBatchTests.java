    public void testSliceAccessorsMatchParent() {
        final int n = randomIntBetween(3, 12);
        final BulkItemRequest[] items = new BulkItemRequest[n];
        for (int d = 0; d < n; d++) {
            final String routing = randomBoolean() ? randomAlphaOfLength(5) : null;
            final IndexRequest req = new IndexRequest("index").id("id-" + d).source(src(d), XContentType.JSON);
            if (routing != null) {
                req.routing(routing);
            }
            items[d] = new BulkItemRequest(d, req);
        }
        final IndexOperationBatch parent = primaryBatch(items, 0, n);
        final int from = randomIntBetween(0, n - 2);
        final int to = randomIntBetween(from + 1, n);
        final IndexOperationBatch slice = parent.slice(from, to);

        // Write known seqNos into the shared buffer so seqNo() returns something meaningful
        for (int d = 0; d < n; d++) {
            ByteUtils.writeLongLE(d + 100L, parent.seqNoBytes().bytes, d * 8);
        }

        for (int i = 0; i < slice.docCount(); i++) {
            final int parentIdx = from + i;
            assertThat("uid at i=" + i, slice.uid(i), equalTo(parent.uid(parentIdx)));
            assertThat("id at i=" + i, slice.id(i), equalTo(parent.id(parentIdx)));
            assertThat("contentType at i=" + i, slice.contentType(i), equalTo(parent.contentType(parentIdx)));
            assertThat("routingString at i=" + i, slice.routingString(i), equalTo(parent.routingString(parentIdx)));
            assertThat(
                "autoGeneratedIdTimestamp at i=" + i,
                slice.autoGeneratedIdTimestamp(i),
                equalTo(parent.autoGeneratedIdTimestamp(parentIdx))
            );
            assertThat("ifSeqNo at i=" + i, slice.ifSeqNo(i), equalTo(parent.ifSeqNo(parentIdx)));
            assertThat("ifPrimaryTerm at i=" + i, slice.ifPrimaryTerm(i), equalTo(parent.ifPrimaryTerm(parentIdx)));
            assertThat("seqNo at i=" + i, slice.seqNo(i), equalTo(parent.seqNo(parentIdx)));
        }
    }

    public void testSliceSharesMutableByteBuffers() {
        final int n = randomIntBetween(3, 10);
        final IndexOperationBatch parent = primaryBatch(n);
        final int from = randomIntBetween(1, n - 1);
        final IndexOperationBatch slice = parent.slice(from, n);

        // The three byte buffers must be the same object in both parent and slice
        assertThat(slice.seqNoBytes(), sameInstance(parent.seqNoBytes()));
        assertThat(slice.primaryTermBytes(), sameInstance(parent.primaryTermBytes()));
        assertThat(slice.versionBytes(), sameInstance(parent.versionBytes()));

        // A write via the slice is visible through the parent (and vice versa)
        final int sliceIdx = randomIntBetween(0, slice.docCount() - 1);
        final long written = randomNonNegativeLong();
        ByteUtils.writeLongLE(written, slice.seqNoBytes().bytes, (slice.offset() + sliceIdx) * 8);

        assertThat("slice sees its own write", slice.seqNo(sliceIdx), equalTo(written));
        assertThat("parent sees the slice's write", parent.seqNo(from + sliceIdx), equalTo(written));

        // Neighbouring parent doc (if any) is unaffected
        if (from > 0) {
            final long before = ByteUtils.readLongLE(parent.seqNoBytes().bytes, (from - 1) * 8);
            assertThat(before, equalTo(SequenceNumbers.UNASSIGNED_SEQ_NO));
        }
    }


    public void testInitFromBulkReplicaCopiesPrimaryResponse() {
        final int n = randomIntBetween(1, 6);
        final BulkItemRequest[] items = new BulkItemRequest[n];
        final long[] seqNos = new long[n];
        final long[] primaryTerms = new long[n];
        final long[] versions = new long[n];
        for (int d = 0; d < n; d++) {
            seqNos[d] = randomNonNegativeLong();
            primaryTerms[d] = randomLongBetween(1, Long.MAX_VALUE);
            versions[d] = randomLongBetween(1, Long.MAX_VALUE);
            final IndexRequest req = new IndexRequest("index").id("id-" + d).source(src(d), XContentType.JSON);
            items[d] = replicaItem(d, req, seqNos[d], primaryTerms[d], versions[d]);
        }
        final IndexOperationBatch batch = IndexOperationBatch.initFromBulk(items, 0, n, null, Engine.Operation.Origin.REPLICA, 1L, 0L);
        for (int d = 0; d < n; d++) {
            assertThat("seqNo at d=" + d, batch.seqNo(d), equalTo(seqNos[d]));
            assertThat("primaryTerm at d=" + d, ByteUtils.readLongLE(batch.primaryTermBytes().bytes, d * 8), equalTo(primaryTerms[d]));
            assertThat("version at d=" + d, ByteUtils.readLongLE(batch.versionBytes().bytes, d * 8), equalTo(versions[d]));
            assertThat(batch.toIndexOp(d).versionType(), nullValue());
            assertThat(batch.toIndexOp(d).version(), equalTo(versions[d]));
            // seqNo is NOT pre-filled with UNASSIGNED_SEQ_NO on the replica path
            assertNotEquals(SequenceNumbers.UNASSIGNED_SEQ_NO, batch.seqNo(d));
        }
    }


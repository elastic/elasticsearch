    public void testInitFromBulkCasSentinelsWhenPartiallySet() {
        final int n = randomIntBetween(2, 8);
        final BulkItemRequest[] items = new BulkItemRequest[n];
        for (int d = 0; d < n; d++) {
            items[d] = new BulkItemRequest(d, new IndexRequest("index").id("id-" + d).source(src(d), XContentType.JSON));
        }
        final int casDoc = randomIntBetween(0, n - 1);
        final long expectedIfSeqNo = randomNonNegativeLong();
        final long expectedIfPrimaryTerm = randomLongBetween(1, Long.MAX_VALUE);
        items[casDoc] = new BulkItemRequest(
            casDoc,
            new IndexRequest("index").id("id-" + casDoc)
                .source(src(casDoc), XContentType.JSON)
                .setIfSeqNo(expectedIfSeqNo)
                .setIfPrimaryTerm(expectedIfPrimaryTerm)
        );
        final IndexOperationBatch batch = primaryBatch(items, 0, n);

        assertThat(batch.ifSeqNo(casDoc), equalTo(expectedIfSeqNo));
        assertThat(batch.ifPrimaryTerm(casDoc), equalTo(expectedIfPrimaryTerm));
        for (int d = 0; d < n; d++) {
            if (d != casDoc) {
                // ifSeqNoBuf uses Arrays.fill(UNASSIGNED_SEQ_NO) before setting the specific entry;
                // ifPrimaryTermBuf relies on Java's 0L default — assert both explicitly.
                assertThat("ifSeqNo sentinel at d=" + d, batch.ifSeqNo(d), equalTo(SequenceNumbers.UNASSIGNED_SEQ_NO));
                assertThat("ifPrimaryTerm sentinel at d=" + d, batch.ifPrimaryTerm(d), equalTo(0L));
            }
        }
    }


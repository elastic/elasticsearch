    public void testInitFromBulkSubRange() {
        // items array is larger than the actual batch range
        final int total = randomIntBetween(3, 12);
        final int from = randomIntBetween(0, total - 2);
        final int to = randomIntBetween(from + 1, total);
        final BulkItemRequest[] allItems = new BulkItemRequest[total];
        for (int d = 0; d < total; d++) {
            allItems[d] = new BulkItemRequest(d, new IndexRequest("index").id("id-" + d).source(src(d), XContentType.JSON));
        }
        final IndexOperationBatch batch = IndexOperationBatch.initFromBulk(
            allItems,
            from,
            to,
            null,
            Engine.Operation.Origin.PRIMARY,
            1L,
            0L
        );
        assertThat(batch.docCount(), equalTo(to - from));
        // initFromBulk always produces offset == 0; offset != 0 arises only via slice()
        assertThat(batch.offset(), equalTo(0));
        // Reads items[from..to) into positions [0..docCount)
        for (int i = 0; i < to - from; i++) {
            assertThat(batch.id(i), equalTo("id-" + (from + i)));
        }
        assertThat(batch.uids().length, equalTo(to - from));
    }


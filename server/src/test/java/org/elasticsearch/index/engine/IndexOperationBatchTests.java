    public void testToIndexOpReflectsLateSeqNoStamping() {
        final int n = randomIntBetween(2, 8);
        final IndexOperationBatch parent = primaryBatch(n);
        final int from = randomIntBetween(0, n - 1);
        final IndexOperationBatch slice = parent.slice(from, n);

        // Stamp random seqNos after construction — toIndexOp must reflect them
        final long[] expected = new long[slice.docCount()];
        for (int i = 0; i < slice.docCount(); i++) {
            expected[i] = randomNonNegativeLong();
            ByteUtils.writeLongLE(expected[i], slice.seqNoBytes().bytes, (slice.offset() + i) * 8);
        }
        for (int i = 0; i < slice.docCount(); i++) {
            assertThat("seqNo at i=" + i, slice.toIndexOp(i).seqNo(), equalTo(expected[i]));
        }
    }

    public void testMaterializeIndexOpsOnSlice() {
        final int n = randomIntBetween(3, 10);
        final IndexOperationBatch parent = primaryBatch(n);
        final int from = randomIntBetween(0, n - 2);
        final int to = randomIntBetween(from + 1, n);
        final IndexOperationBatch slice = parent.slice(from, to);

        final List<Engine.Index> ops = slice.materializeIndexOps();
        assertThat(ops.size(), equalTo(to - from));
        for (int i = 0; i < ops.size(); i++) {
            assertThat(ops.get(i).id(), equalTo(slice.id(i)));
            assertThat(ops.get(i).id(), equalTo(parent.id(from + i)));
        }
    }

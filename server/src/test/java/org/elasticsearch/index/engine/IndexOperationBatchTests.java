    private static BulkItemRequest[] items(int n) {
        final BulkItemRequest[] items = new BulkItemRequest[n];
        for (int d = 0; d < n; d++) {
            items[d] = new BulkItemRequest(d, new IndexRequest("index").id("doc-" + d).source(src(d), XContentType.JSON));
        }
        return items;
    }

    private static IndexOperationBatch primaryBatch(int n) {
        return IndexOperationBatch.initFromBulk(items(n), 0, n, null, Engine.Operation.Origin.PRIMARY, 1L, 0L);
    }

    private static IndexOperationBatch primaryBatch(BulkItemRequest[] items, int from, int to) {
        return IndexOperationBatch.initFromBulk(items, from, to, null, Engine.Operation.Origin.PRIMARY, 1L, 0L);
    }

    private static BytesArray src(int d) {
        return new BytesArray("{\"n\":" + d + "}");
    }

    private static BulkItemRequest replicaItem(int id, IndexRequest request, long seqNo, long primaryTerm, long version) {
        final BulkItemRequest item = mock(BulkItemRequest.class);
        doReturn(request).when(item).request();
        when(item.getPrimaryResponse()).thenReturn(
            BulkItemResponse.success(
                id,
                DocWriteRequest.OpType.INDEX,
                new IndexResponse(new ShardId("index", "_na_", 0), request.id(), seqNo, primaryTerm, version, true)
            )
        );
        return item;
    }

    private static EscfBatch escfBatch(int docCount) throws IOException {
        final List<BytesReference> sources = new ArrayList<>(docCount);
        for (int d = 0; d < docCount; d++) {
            sources.add(src(d));
        }
        return EscfEncoder.encode(sources, XContentType.JSON);
    }

    public void testInitFromBulkMapsPerDocFields() {
        final int n = randomIntBetween(1, 16);
        final BulkItemRequest[] items = new BulkItemRequest[n];
        for (int d = 0; d < n; d++) {
            final IndexRequest req = new IndexRequest("index").id("id-" + d).source(src(d), XContentType.JSON);
            items[d] = new BulkItemRequest(d, req);
        }
        final IndexOperationBatch batch = primaryBatch(items, 0, n);

        assertThat(batch.docCount(), equalTo(n));
        assertThat(batch.offset(), equalTo(0));
        for (int d = 0; d < n; d++) {
            assertThat(batch.id(d), equalTo("id-" + d));
            assertThat(batch.uid(d), equalTo(Uid.encodeId("id-" + d)));
            assertThat(batch.contentType(d), equalTo(XContentType.JSON));
            assertThat(batch.routingString(d), nullValue());
            assertThat(batch.autoGeneratedIdTimestamp(d), equalTo(IndexRequest.UNSET_AUTO_GENERATED_TIMESTAMP));
            assertFalse(batch.toIndexOp(d).isRetry());
        }
    }


    public void testInitFromBulkRoutingArrayAllocatedLazily() {
        final int n = randomIntBetween(2, 8);
        final BulkItemRequest[] items = new BulkItemRequest[n];
        for (int d = 0; d < n; d++) {
            items[d] = new BulkItemRequest(d, new IndexRequest("index").id("id-" + d).source(src(d), XContentType.JSON));
        }
        // No routing on any doc → routings array stays null
        final IndexOperationBatch noRouting = primaryBatch(items, 0, n);
        assertThat(noRouting.routings(), nullValue());
        for (int d = 0; d < n; d++) {
            assertThat(noRouting.routingString(d), nullValue());
        }

        // Add routing to a random subset, rebuild
        final int routedDoc = randomIntBetween(0, n - 1);
        final String expectedRouting = randomAlphaOfLength(6);
        items[routedDoc] = new BulkItemRequest(
            routedDoc,
            new IndexRequest("index").id("id-" + routedDoc).source(src(routedDoc), XContentType.JSON).routing(expectedRouting)
        );
        final IndexOperationBatch withRouting = primaryBatch(items, 0, n);
        assertNotNull(withRouting.routings());
        assertThat(withRouting.routings().length, equalTo(n));
        assertThat(withRouting.routingString(routedDoc), equalTo(expectedRouting));
        for (int d = 0; d < n; d++) {
            if (d != routedDoc) {
                assertThat(withRouting.routingString(d), nullValue());
            }
        }
    }


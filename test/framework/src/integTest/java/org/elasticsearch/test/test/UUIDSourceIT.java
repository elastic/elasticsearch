package org.elasticsearch.test.test;

import com.carrotsearch.randomizedtesting.annotations.Repeat;

import org.elasticsearch.action.DocWriteResponse;
import org.elasticsearch.action.bulk.BulkRequest;
import org.elasticsearch.action.index.IndexRequest;
import org.elasticsearch.action.index.IndexResponse;
import org.elasticsearch.cluster.service.ClusterService;
import org.elasticsearch.core.SuppressForbidden;
import org.elasticsearch.test.ESIntegTestCase;
import org.junit.AfterClass;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashSet;
import java.util.List;

import static org.elasticsearch.test.hamcrest.ElasticsearchAssertions.assertAcked;
import static org.elasticsearch.test.hamcrest.ElasticsearchAssertions.assertNoFailures;

/** Auto-generated IDs and their shards reproduce across repetitions of a test method on a reused suite cluster. */
@ESIntegTestCase.ClusterScope(scope = ESIntegTestCase.Scope.SUITE, numDataNodes = 2, numClientNodes = 0, supportsDedicatedMasters = false)
public class UUIDSourceIT extends ESIntegTestCase {

    private static List<GeneratedId> expectedIds;
    private static List<String> expectedNodeIds;

    @SuppressForbidden(reason = "Constant-seed repetitions verify UUID state resets across the actual test lifecycle")
    @Repeat(iterations = 3, useConstantSeed = true)
    public void testAutoGeneratedIdsReproduce() {
        final var nodes = Arrays.stream(internalCluster().getNodeNames()).sorted().toList();
        final var nodeIds = nodes.stream()
            .map(name -> internalCluster().getInstance(ClusterService.class, name).localNode().getEphemeralId())
            .toList();
        final var ids = new ArrayList<GeneratedId>();
        ids.addAll(indexDocuments("standard", false, false, nodes));
        ids.addAll(indexDocuments("logs", true, false, nodes));
        ids.addAll(indexDocuments("routed-logs", true, true, nodes));

        if (expectedIds == null) {
            expectedIds = List.copyOf(ids);
            expectedNodeIds = nodeIds;
        } else {
            assertEquals("the test must reuse the same running nodes", expectedNodeIds, nodeIds);
            assertEquals("the same test seed must reproduce document IDs and their shards", expectedIds, ids);
        }
        logger.info("generated IDs and shards: {}", ids);
    }

    public void testUnrelatedIndexing() {
        assertAcked(prepareCreate("unrelated").setSettings(indexSettings(3, 0)));
        for (int i = 0; i < 10; i++) {
            client().prepareIndex("unrelated").setSource("value", i).get();
        }
    }

    private List<GeneratedId> indexDocuments(String index, boolean logsdb, boolean routingHash, List<String> nodes) {
        final var settings = indexSettings(3, 0).put("index.mode", logsdb ? "logsdb" : "standard");
        if (routingHash) {
            settings.put("index.logsdb.route_on_sort_fields", true)
                .putList("index.routing_path", "host.name")
                .putList("index.sort.field", "host.name", "@timestamp");
        }
        assertAcked(prepareCreate(index).setSettings(settings).setMapping("@timestamp", "type=date", "host.name", "type=keyword"));
        ensureGreen(index);

        final var ids = new ArrayList<GeneratedId>();
        for (String node : nodes) {
            final var client = internalCluster().client(node);
            final var bulk = new BulkRequest();
            for (int i = 0; i < 10; i++) {
                bulk.add(new IndexRequest(index).source("@timestamp", "2026-01-01T00:00:00Z", "host.name", "host-" + i));
            }
            final var response = client.bulk(bulk).actionGet();
            assertNoFailures(response);
            for (var item : response) {
                final IndexResponse indexed = item.getResponse();
                assertEquals(DocWriteResponse.Result.CREATED, indexed.getResult());
                assertEquals(routingHash ? 26 : 20, indexed.getId().length());
                ids.add(new GeneratedId(index, indexed.getId(), indexed.getShardId().id()));
                assertTrue(client.prepareGet(index, indexed.getId()).get().isExists());
            }
        }
        assertEquals(ids.size(), new HashSet<>(ids.stream().map(GeneratedId::id).toList()).size());
        return ids;
    }

    @AfterClass
    public static void clearExpectedIds() {
        expectedIds = null;
        expectedNodeIds = null;
    }

    private record GeneratedId(String index, String id, int shard) {}
}

package org.elasticsearch.xpack.esql.qa.publicdata.oracle;

import org.elasticsearch.core.SuppressForbidden;
import org.elasticsearch.xpack.esql.qa.publicdata.catalog.VariantSpec;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.TimeUnit;

/**
 * The primary oracle: {@code clickhouse local}. Chosen because the issue names ClickHouse and
 * because ClickBench's canonical queries are ClickHouse SQL, so those run verbatim — no dialect
 * hop whose errors could freeze into the expectations. The binary is resolved from
 * {@code $CLICKHOUSE_BIN} (default {@code ~/.local/bin/clickhouse}) — never a hard-coded path,
 * since the machine this runs on varies.
 */
public class ClickHouseLocalOracle implements Oracle {

    private final Path binary;

    public ClickHouseLocalOracle() {
        this(resolveBinary());
    }

    public ClickHouseLocalOracle(Path binary) {
        this.binary = binary;
    }

    static Path resolveBinary() {
        String fromEnvironment = System.getenv("CLICKHOUSE_BIN");
        if (fromEnvironment != null && fromEnvironment.isEmpty() == false) {
            return Path.of(fromEnvironment);
        }
        return Path.of(System.getProperty("user.home"), ".local", "bin", "clickhouse");
    }

    @Override
    public String name() {
        try {
            OracleResult version = execute(List.of(binary.toString(), "local", "-q", "SELECT version()"));
            return "clickhouse local " + version.stdout().trim();
        } catch (IOException e) {
            return "clickhouse local (version unavailable: " + e.getMessage() + ")";
        }
    }

    @Override
    public boolean canRead(VariantSpec variant) {
        // clickhouse local reads all four suite formats; non-seekable single-stream objects are
        // fine too since authoring reads a local scratch copy.
        return true;
    }

    @Override
    public String renderScript(List<OracleQuery> queries) {
        StringBuilder script = new StringBuilder("-- generated by OracleScriptGenerator; authoring aid only, never checked in\n");
        for (OracleQuery query : queries) {
            script.append("-- test: ").append(query.testName()).append('\n');
            String sql = query.sql().trim();
            script.append(sql, 0, sql.endsWith(";") ? sql.length() - 1 : sql.length());
            script.append(" FORMAT TSVWithNames;\n\n");
        }
        return script.toString();
    }

    @Override
    public OracleResult run(Path script) throws IOException {
        return execute(List.of(binary.toString(), "local", "--queries-file", script.toString()));
    }

    @SuppressForbidden(reason = "authoring-only process wrapper: ProcessBuilder redirection requires java.io.File, and the JVM-default"
        + " temp location is exactly right for transient oracle output outside any test framework")
    private OracleResult execute(List<String> command) throws IOException {
        Path stdout = Files.createTempFile("oracle-stdout", ".out");
        Path stderr = Files.createTempFile("oracle-stderr", ".err");
        try {
            Process process = new ProcessBuilder(command).redirectOutput(stdout.toFile()).redirectError(stderr.toFile()).start();
            boolean finished = process.waitFor(30, TimeUnit.MINUTES);
            if (finished == false) {
                process.destroyForcibly();
                throw new IOException("oracle run timed out: " + String.join(" ", command));
            }
            return new OracleResult(
                process.exitValue(),
                Files.readString(stdout, StandardCharsets.UTF_8),
                Files.readString(stderr, StandardCharsets.UTF_8)
            );
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new IOException("interrupted while running the oracle", e);
        } finally {
            Files.deleteIfExists(stdout);
            Files.deleteIfExists(stderr);
        }
    }
}

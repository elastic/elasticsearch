package org.elasticsearch.xpack.esql.qa.single_node;

import org.elasticsearch.client.ResponseException;
import org.elasticsearch.common.Strings;
import org.elasticsearch.xcontent.XContentType;
import org.elasticsearch.xpack.esql.CsvSpecReader.CsvTestCase;
import org.elasticsearch.xpack.esql.CsvTestUtils;
import org.elasticsearch.xpack.esql.qa.rest.RestEsqlTestCase;
import org.elasticsearch.xpack.esql.qa.rest.RestEsqlTestCase.RequestObjectBuilder;

import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static org.elasticsearch.xpack.esql.action.EsqlCapabilities.Cap.EXEMPLARS_SETTING_DEVELOPMENT_V8;
import static org.elasticsearch.xpack.esql.qa.rest.RestEsqlTestCase.hasCapabilities;
import static org.hamcrest.Matchers.anyOf;
import static org.hamcrest.Matchers.equalTo;
import static org.hamcrest.Matchers.hasSize;

/**
 * Abstract base for per-csv-spec-file test classes generated by the Gradle build.
 * Each generated subclass covers one csv-spec file and runs every {@code TS ... | STATS} and {@code PROMQL} test case of it with
 * the {@code exemplars} request setting, as a smoke test of the exemplars query rewrite: the metrics query must be accepted and
 * rewritten into a well-formed exemplars query over every metrics query shape the specs cover, whether or not an exemplar data
 * stream exists for the metrics it reads. Results are not compared to the spec's expected results, which describe the metrics
 * query; the dedicated exemplars spec covers the results of the rewrite.
 * <p>
 * Most time series specs read the plain {@code k8s} index, which no exemplar data stream can be derived from, so the rewrite would
 * stop before translating the query's filters. To exercise the translation, queries over {@code k8s} are redirected to the
 * {@code metrics-k8s} data stream of the exemplars fixture, which holds the same data under the same mapping and derives the
 * (non-existent) {@code exemplars-k8s} data stream.
 */
public abstract class AbstractEsqlSpecExemplarsSmokeIT extends AbstractEsqlSpecIT {

    /** {@code SET ...;} statements preceding the query, with the {@code ;} separator the spec reader keeps. */
    private static final Pattern LEADING_SET_STATEMENTS = Pattern.compile("(?is)^(\\s*SET\\s[^;]*;)+\\s*");
    private static final Pattern TS_WITH_STATS = Pattern.compile("(?is)^TS\\s.*\\bSTATS\\b.*");
    private static final Pattern PROMQL = Pattern.compile("(?is)^PROMQL\\s.*");
    /**
     * The {@code k8s} index as the (only) source of a {@code TS} or {@code PROMQL index=} command. Patterns and multi-index
     * expressions are left alone.
     */
    private static final Pattern K8S_INDEX = Pattern.compile("(?i)(\\bTS\\s+|\\bindex\\s*=\\s*\"?)k8s(?![\\w.*-])");
    private static final String METRICS_K8S_INDEX = "metrics-k8s";

    /** Prefixes of the columns an exemplars query returns, see {@code ExemplarsRewriter#exemplarProjections}. */
    private static final List<String> EXEMPLAR_COLUMNS = List.of("@timestamp", "metric_name", "value", "trace_id", "span_id");

    /**
     * Messages of the verification errors the exemplars setting raises for metrics queries it does not support. A test case running
     * into one of them is skipped: the rejection is the documented behavior, not an explosion.
     */
    private static final List<String> UNSUPPORTED_QUERY_MESSAGES = List.of(
        "supports at most one TS ... | STATS or PROMQL command",
        "The exemplars setting does not support views yet"
    );

    protected AbstractEsqlSpecExemplarsSmokeIT(
        String fileName,
        String groupName,
        String testName,
        Integer lineNumber,
        CsvTestCase testCase,
        String instructions
    ) {
        super(fileName, groupName, testName, lineNumber, testCase, instructions);
    }

    @Override
    protected void shouldSkipTest(String testName) throws IOException {
        super.shouldSkipTest(testName);
        CsvTestUtils.assumeTrueLogging(
            "Cluster needs to support the exemplars setting",
            hasCapabilities(adminClient(), List.of(EXEMPLARS_SETTING_DEVELOPMENT_V8.capabilityName()))
        );
        CsvTestUtils.assumeFalseLogging(
            "Tests of the exemplars setting itself run as they are",
            testCase.requiredCapabilities.contains(EXEMPLARS_SETTING_DEVELOPMENT_V8.capabilityName())
        );
        CsvTestUtils.assumeFalseLogging(
            "dataset-backed spec; covered by the external-source suites",
            testCase.datasetSources.isEmpty() == false
        );
        CsvTestUtils.assumeTrueLogging("Only TS ... | STATS and PROMQL queries aggregate metrics", isMetricsQuery(testCase.query));
    }

    /**
     * Whether the query, after any leading {@code SET} statements, is a {@code TS} command with a {@code STATS} or a {@code PROMQL}
     * command. Queries that only contain these in a subquery or {@code FORK} branch are not considered: they are not metrics queries
     * at their top level.
     */
    static boolean isMetricsQuery(String query) {
        String command = LEADING_SET_STATEMENTS.matcher(query).replaceFirst("");
        return PROMQL.matcher(command).matches() || TS_WITH_STATS.matcher(command).matches();
    }

    @Override
    protected void doTest() throws Throwable {
        String exemplarsSetting = randomExemplarsSetting();
        String query = redirectK8sToMetricsDataStream(testCase.query);

        RequestObjectBuilder builder = new RequestObjectBuilder(randomFrom(XContentType.values())).query(query)
            .settings("{\"exemplars\": " + exemplarsSetting + "}");
        if (Strings.isNullOrEmpty(testCase.requestTimeRangeGte) == false) {
            // TSTEP and PROMQL range queries take their time range from the request filter
            String gte = testCase.requestTimeRangeGte;
            String lte = testCase.requestTimeRangeLte;
            builder.filter(b -> {
                b.startObject("range");
                b.startObject("@timestamp");
                b.field("gte", gte);
                b.field("lte", lte);
                b.endObject();
                b.endObject();
            });
        }
        Map<String, Object> answer;
        try {
            // Warnings describe the execution of the metrics query, which does not run, or fields of the exemplar data streams, so
            // the warnings the spec expects do not apply and the ones the exemplars query raises are not asserted.
            answer = RestEsqlTestCase.runEsql(builder, (warnings, context) -> {}, profileLogger, mode);
        } catch (ResponseException e) {
            // The error is parsed instead of searching the raw body: the request format is random and e.g. YAML wraps long strings
            // at an arbitrary column, which can split a message we look for.
            Map<String, Object> error = entityAsMap(e.getResponse());
            if (e.getResponse().getStatusLine().getStatusCode() == 400) {
                List<String> reasons = errorReasons(error);
                for (String message : UNSUPPORTED_QUERY_MESSAGES) {
                    CsvTestUtils.assumeFalseLogging(
                        "Metrics query is not supported with exemplars: " + error,
                        reasons.stream().anyMatch(reason -> reason.contains(message))
                    );
                }
            }
            throw new AssertionError("Exemplars query failed for [" + query + "] with exemplars=" + exemplarsSetting + ": " + error, e);
        }
        assertExemplarColumns(answer, exemplarsSetting.contains("include_timeseries\": true"));
    }

    /** The {@code reason} of an error response and of each of its {@code root_cause}s. */
    private static List<String> errorReasons(Map<String, Object> response) {
        List<String> reasons = new ArrayList<>();
        if (response.get("error") instanceof Map<?, ?> error) {
            if (error.get("reason") instanceof String reason) {
                reasons.add(reason);
            }
            if (error.get("root_cause") instanceof List<?> rootCauses) {
                for (Object rootCause : rootCauses) {
                    if (rootCause instanceof Map<?, ?> cause && cause.get("reason") instanceof String reason) {
                        reasons.add(reason);
                    }
                }
            }
        }
        return reasons;
    }

    private static String randomExemplarsSetting() {
        return switch (between(0, 3)) {
            case 0 -> "true";
            case 1 -> "{\"limit\": " + between(1, 100) + "}";
            case 2 -> "{\"include_timeseries\": true}";
            case 3 -> "{\"limit\": " + between(1, 100) + ", \"include_timeseries\": true}";
            default -> throw new AssertionError("unexpected exemplars setting");
        };
    }

    static String redirectK8sToMetricsDataStream(String query) {
        Matcher matcher = K8S_INDEX.matcher(query);
        return matcher.replaceAll(result -> Matcher.quoteReplacement(result.group(1) + METRICS_K8S_INDEX));
    }

    /**
     * An exemplars query either has no columns at all, when no exemplar data stream could be derived from the indices of the metrics
     * query, or the exemplar columns followed by {@code _timeseries} if requested and the {@code _source} of the exemplars.
     */
    private static void assertExemplarColumns(Map<String, Object> answer, boolean includeTimeseries) {
        @SuppressWarnings("unchecked")
        List<Map<String, String>> columns = (List<Map<String, String>>) answer.get("columns");
        assertNotNull(columns);
        List<String> names = columns.stream().map(column -> column.get("name")).toList();
        if (names.isEmpty()) {
            @SuppressWarnings("unchecked")
            List<List<Object>> values = (List<List<Object>>) answer.get("values");
            assertThat("a query without columns has no rows", values, anyOf(equalTo(null), hasSize(0)));
            return;
        }
        List<String> expected = new ArrayList<>(EXEMPLAR_COLUMNS);
        if (includeTimeseries) {
            expected.add("_timeseries");
        }
        expected.add("_source");
        assertThat(names, equalTo(expected));
        // Columns the exemplar data streams do not map are nullified.
        for (Map<String, String> column : columns) {
            if (column.get("name").equals("_source") == false) {
                assertThat(column.get("type"), anyOf(equalTo("null"), equalTo(expectedType(column.get("name")))));
            }
        }
    }

    private static String expectedType(String column) {
        return switch (column) {
            case "@timestamp" -> "date";
            case "value" -> "double";
            case "metric_name", "trace_id", "span_id", "_timeseries" -> "keyword";
            default -> throw new AssertionError("unexpected exemplar column [" + column + "]");
        };
    }
}

package org.elasticsearch.xpack.esql.qa.single_node;

import org.elasticsearch.logging.Logger;
import org.elasticsearch.xpack.esql.CsvSpecReader.CsvTestCase;
import org.elasticsearch.xpack.esql.CsvTestUtils.ExpectedResults;
import org.elasticsearch.xpack.esql.LoadAllFromLoad;

import java.util.List;
import java.util.Map;

/**
 * Abstract base for per-csv-spec-file test classes generated by the Gradle build. Each generated subclass covers one csv-spec file and
 * runs every query that sets {@code unmapped_fields="load"} with {@code "LOAD_ALL"} instead, expecting the results of the original query.
 * See {@link LoadAllFromLoad}.
 */
public abstract class AbstractEsqlSpecLoadAllIT extends AbstractEsqlSpecIT {

    private final String testId;

    protected AbstractEsqlSpecLoadAllIT(
        String fileName,
        String groupName,
        String testName,
        Integer lineNumber,
        CsvTestCase testCase,
        String instructions
    ) {
        super(fileName, groupName, testName, lineNumber, testCase, instructions);
        this.testId = groupName + "." + testName;
    }

    @Override
    protected void doTest() throws Throwable {
        assumeTrue("the query does not set unmapped_fields=\"load\"", LoadAllFromLoad.usesLoad(testCase.query));
        String skipReason = LoadAllFromLoad.skipReason(testId);
        assumeTrue(skipReason, skipReason == null);
        testCase.adjustExpectedWarnings(LoadAllFromLoad::expectedWarning);
        doTest(LoadAllFromLoad.toLoadAll(testCase.query));
    }

    @Override
    protected void assertResults(
        ExpectedResults expected,
        List<Map<String, String>> actualColumns,
        List<List<Object>> actualValues,
        Logger logger
    ) {
        var results = LoadAllFromLoad.withoutUnmappedFieldsColumn(
            expected.columnNames().contains(LoadAllFromLoad.UNMAPPED_FIELDS_COLUMN),
            actualColumns,
            actualValues
        );
        super.assertResults(expected, results.columns(), results.values(), logger);
    }
}

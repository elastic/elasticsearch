package org.elasticsearch.xpack.esql.expression.function.fulltext;

import org.apache.lucene.index.memory.MemoryIndex;
import org.apache.lucene.search.IndexSearcher;
import org.apache.lucene.search.Query;
import org.apache.lucene.search.TopDocs;
import org.apache.lucene.util.BytesRef;
import org.apache.lucene.util.RamUsageEstimator;
import org.elasticsearch.common.Strings;
import org.elasticsearch.compute.data.Block;
import org.elasticsearch.compute.data.BytesRefBlock;
import org.elasticsearch.compute.data.DoubleVector;
import org.elasticsearch.compute.data.LongBlock;
import org.elasticsearch.compute.data.Page;
import org.elasticsearch.compute.expression.ExpressionEvaluator;
import org.elasticsearch.compute.operator.DriverContext;
import org.elasticsearch.compute.operator.Warnings;
import org.elasticsearch.core.Releasables;
import org.elasticsearch.index.analysis.NamedAnalyzer;
import org.elasticsearch.xpack.esql.core.tree.Source;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.util.ArrayList;
import java.util.List;

/**
 * Scores the rows of a {@code MATCH} or {@code MATCH_PHRASE} with {@code similarity_function: bm25} on text that has
 * no index behind it. Each row is indexed into a one-row {@link MemoryIndex}, and Lucene scores the compiled query
 * against it through a {@link SuppliedStatisticsSearcher}, which supplies the statistics of the whole statistics
 * group. Rows that do not match score 0.
 * <p>
 * The statistics arrive as k + 2 expressions, usually the literals the statistics pass inlined. Each evaluator reads
 * them once, from the first page it sees, so columns and folded literals behave the same way. That per-driver state
 * is why this evaluator is written by hand instead of generated by {@code @Evaluator}.
 * <p>
 * When a statistic had to be clamped, or the statistics are empty while a row matches, the data changed between
 * the passes. The query then gets one warning, and the affected rows score with the clamped values, or 0.
 */
final class RuntimeBm25ScoreEvaluator implements ExpressionEvaluator {

    static final String DRIFT_WARNING =
        "the statistics and scoring passes read different data for [%s]; BM25 scores use clamped or empty statistics";

    private static final long BASE_RAM_BYTES_USED = RamUsageEstimator.shallowSizeOfInstance(RuntimeBm25ScoreEvaluator.class);

    /**
     * @param fieldSource the source text of the scored field, used in the warning and in PROFILE
     * @param analyzer    the values analyzer, with the position increment gap of an indexed {@code text} field
     * @param terms       the sorted term list of the statistics group, in the order of the df statistics
     * @param statistics  N, the summed length and one df per term, in that order
     */
    record Factory(
        Source source,
        String fieldSource,
        ExpressionEvaluator.Factory field,
        Query query,
        NamedAnalyzer analyzer,
        List<BytesRef> terms,
        List<ExpressionEvaluator.Factory> statistics
    ) implements ExpressionEvaluator.Factory {

        @Override
        public ExpressionEvaluator get(DriverContext context) {
            ExpressionEvaluator fieldEvaluator = null;
            List<ExpressionEvaluator> statisticEvaluators = new ArrayList<>(statistics.size());
            boolean success = false;
            try {
                fieldEvaluator = field.get(context);
                for (ExpressionEvaluator.Factory statistic : statistics) {
                    statisticEvaluators.add(statistic.get(context));
                }
                ExpressionEvaluator evaluator = new RuntimeBm25ScoreEvaluator(this, context, fieldEvaluator, statisticEvaluators);
                success = true;
                return evaluator;
            } finally {
                if (success == false) {
                    Releasables.closeExpectNoException(fieldEvaluator, Releasables.wrap(statisticEvaluators));
                }
            }
        }

        @Override
        public String toString() {
            return "RuntimeBm25ScoreEvaluator[" + description() + "]";
        }

        private String description() {
            return "field=" + fieldSource + ", analyzer=" + analyzer.name() + ", similarity=" + SuppliedStatisticsSearcher.SIMILARITY;
        }
    }

    private final Factory factory;
    private final DriverContext driverContext;
    private final ExpressionEvaluator field;
    private final List<ExpressionEvaluator> statisticEvaluators;
    private final MemoryIndex memoryIndex = new MemoryIndex();
    private BytesRef scratch = new BytesRef();
    private Bm25Statistics statistics;
    private Warnings warnings;

    private RuntimeBm25ScoreEvaluator(
        Factory factory,
        DriverContext driverContext,
        ExpressionEvaluator field,
        List<ExpressionEvaluator> statisticEvaluators
    ) {
        this.factory = factory;
        this.driverContext = driverContext;
        this.field = field;
        this.statisticEvaluators = statisticEvaluators;
        // Norms are computed with the similarity the searcher scores with, as an indexed text field does.
        this.memoryIndex.setSimilarity(SuppliedStatisticsSearcher.SIMILARITY);
    }

    @Override
    public Block eval(Page page) {
        int positions = page.getPositionCount();
        if (statistics == null && positions > 0) {
            statistics = readStatistics(page);
        }
        try (
            BytesRefBlock values = (BytesRefBlock) field.eval(page);
            DoubleVector.FixedBuilder scores = driverContext.blockFactory().newDoubleVectorFixedBuilder(positions)
        ) {
            for (int p = 0; p < positions; p++) {
                scores.appendDouble(score(values, p));
            }
            return scores.build().asBlock();
        }
    }

    private Bm25Statistics readStatistics(Page page) {
        Long[] values = new Long[statisticEvaluators.size()];
        for (int i = 0; i < values.length; i++) {
            try (Block block = statisticEvaluators.get(i).eval(page)) {
                values[i] = block.isNull(0) ? null : ((LongBlock) block).getLong(block.getFirstValueIndex(0));
            }
        }
        return Bm25Statistics.of(factory.terms(), values);
    }

    private double score(BytesRefBlock values, int position) {
        if (values.isNull(position)) {
            return 0.0;
        }
        scratch = RuntimeSearch.indexRow(memoryIndex, values, position, factory.analyzer(), scratch);
        IndexSearcher rowSearcher = memoryIndex.createSearcher();
        try {
            if (statistics.isEmpty()) {
                // A matching row means the statistics pass missed rows that the scoring pass reads.
                if (rowSearcher.count(factory.query()) > 0) {
                    warn();
                }
                return 0.0;
            }
            SuppliedStatisticsSearcher searcher = new SuppliedStatisticsSearcher(rowSearcher.getIndexReader(), statistics);
            TopDocs topDocs = searcher.search(factory.query(), 1);
            if (searcher.clampFired()) {
                warn();
            }
            return topDocs.scoreDocs.length > 0 ? topDocs.scoreDocs[0].score : 0.0;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private void warn() {
        if (warnings == null) {
            warnings = driverContext.createWarnings(factory.source());
        }
        warnings.registerWarning(Strings.format(DRIFT_WARNING, factory.fieldSource()));
    }

    @Override
    public long baseRamBytesUsed() {
        long bytes = BASE_RAM_BYTES_USED + field.baseRamBytesUsed();
        for (ExpressionEvaluator statistic : statisticEvaluators) {
            bytes += statistic.baseRamBytesUsed();
        }
        return bytes;
    }

    /** The PROFILE text: the field, the analyzer, the similarity with k1 and b, and the statistics once read. */
    @Override
    public String toString() {
        return "RuntimeBm25ScoreEvaluator[" + factory.description() + (statistics == null ? "" : ", " + statistics) + "]";
    }

    @Override
    public void close() {
        Releasables.closeExpectNoException(field, Releasables.wrap(statisticEvaluators));
    }
}

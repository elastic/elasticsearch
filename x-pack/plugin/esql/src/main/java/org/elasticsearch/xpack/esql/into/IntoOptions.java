package org.elasticsearch.xpack.esql.into;

import java.util.Locale;

/**
 * The options an {@code INTO} command accepts after its destination, in a {@code WITH} map as for {@code RERANK}:
 * {@code INTO dst WITH { "collisions": "keep", "refresh": false }}.
 * <p>
 * Option names and the values of {@code collisions} are case-insensitive. A bad name or value is reported as an
 * {@link IllegalArgumentException} whose message names the option, which the parser turns into a {@code ParsingException}
 * at the option's position.
 *
 * @param collisions what to do with a row whose document id already exists in the destination
 * @param refresh    whether to refresh the destination once every row has been written, so the rows are searchable
 *                   by the time the query returns. On by default, since a query that writes is usually followed by
 *                   one that reads; {@code refresh=false} leaves the rows to the destination's own refresh interval.
 * @param keepGoing  whether a row the destination refuses (a value its mapping cannot take, say) is skipped and
 *                   counted rather than failing the query. Collisions are governed by {@code collisions} either way,
 *                   and a bulk that fails as a whole always fails the query, since none of it was written.
 * @param approximate whether an approximated result may be written. Approximation is refused otherwise, since the
 *                    rows written would be an estimate with nothing in the destination to say so.
 */
public record IntoOptions(Collisions collisions, boolean refresh, boolean keepGoing, boolean approximate) {

    public static final String COLLISIONS = "collisions";
    public static final String REFRESH = "refresh";
    public static final String KEEP_GOING = "keep_going";
    public static final String APPROXIMATE = "approximate";

    public static final IntoOptions DEFAULT = new IntoOptions(Collisions.ABORT, true, false, false);

    /**
     * How a row whose document id already exists in the destination is handled. Ids are normally generated by the
     * destination, in which case nothing collides. They come from the query when its output has an {@code _id}
     * column, and from the destination itself when it synthesizes them (time series indices derive one from
     * {@code _tsid} and {@code @timestamp}); either way a collision surfaces as a conflict on the write.
     */
    public enum Collisions {
        /** The query fails on the first collision. The default. */
        ABORT,
        /** The existing document is replaced. Not available for data streams, which only accept new documents. */
        REPLACE,
        /** The existing document is kept and the row is counted as a version conflict. */
        KEEP;

        public static Collisions parse(Object value) {
            if (value instanceof String string) {
                for (Collisions collisions : values()) {
                    if (collisions.name().equalsIgnoreCase(string)) {
                        return collisions;
                    }
                }
            }
            throw new IllegalArgumentException(
                "invalid value [" + value + "] for option [" + COLLISIONS + "], expected one of [\"abort\", \"replace\", \"keep\"]"
            );
        }

        @Override
        public String toString() {
            return name().toLowerCase(Locale.ROOT);
        }
    }

    /**
     * Returns a copy with the named option set. {@code collisions} takes a string and the others a boolean, as typed in
     * the query's {@code WITH} map; a value of another type is refused rather than read as text.
     */
    public IntoOptions with(String name, Object value) {
        return switch (name.toLowerCase(Locale.ROOT)) {
            case COLLISIONS -> new IntoOptions(Collisions.parse(value), refresh, keepGoing, approximate);
            case REFRESH -> new IntoOptions(collisions, booleanValue(REFRESH, value), keepGoing, approximate);
            case KEEP_GOING -> new IntoOptions(collisions, refresh, booleanValue(KEEP_GOING, value), approximate);
            case APPROXIMATE -> new IntoOptions(collisions, refresh, keepGoing, booleanValue(APPROXIMATE, value));
            default -> throw new IllegalArgumentException(
                "unknown option ["
                    + name
                    + "] for INTO, expected one of ["
                    + String.join(", ", COLLISIONS, REFRESH, KEEP_GOING, APPROXIMATE)
                    + "]"
            );
        };
    }

    private static boolean booleanValue(String name, Object value) {
        if (value instanceof Boolean bool) {
            return bool;
        }
        throw new IllegalArgumentException("invalid value [" + value + "] for option [" + name + "], expected a boolean, true or false");
    }

    @Override
    public String toString() {
        return COLLISIONS
            + "="
            + collisions
            + ", "
            + REFRESH
            + "="
            + refresh
            + ", "
            + KEEP_GOING
            + "="
            + keepGoing
            + ", "
            + APPROXIMATE
            + "="
            + approximate;
    }
}

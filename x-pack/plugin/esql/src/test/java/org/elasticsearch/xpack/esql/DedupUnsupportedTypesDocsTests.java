package org.elasticsearch.xpack.esql;

import org.elasticsearch.core.PathUtils;
import org.elasticsearch.logging.LogManager;
import org.elasticsearch.logging.Logger;
import org.elasticsearch.test.ESTestCase;
import org.elasticsearch.xpack.esql.core.type.DataType;
import org.elasticsearch.xpack.esql.expression.function.DocsV3Support;
import org.junit.AfterClass;

import java.io.IOException;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

import static org.hamcrest.Matchers.containsString;
import static org.hamcrest.Matchers.not;

/**
 * Generates the unsupported-type sentence in the {@code DEDUP} docs from {@link DataType#isGroupable()},
 * so the page cannot list a type the command accepts or omit one it rejects.
 */
public class DedupUnsupportedTypesDocsTests extends ESTestCase {
    /**
     * Non-groupable types that never appear as a {@code DEDUP} column. Small numeric types are excluded
     * separately because they are widened on load. {@code unsupported} is ignored rather than rejected,
     * {@code object} resolves to its subfields, {@code _doc} is implicit, and partial aggregates and
     * time-series metadata never reach the command.
     */
    private static final Set<DataType> NOT_A_DEDUP_COLUMN = Set.of(
        DataType.UNSUPPORTED,
        DataType.OBJECT,
        DataType.DOC_DATA_TYPE,
        DataType.PARTIAL_AGG,
        DataType.TIME_SERIES_METADATA_DATA_TYPE
    );

    public void testSnippetListsExactlyTheRejectedTypes() {
        String rendered = renderSnippet();
        for (DataType type : DataType.values()) {
            String mention = "`" + type.typeName() + "`";
            if (rejectedByDedup(type)) {
                assertThat(type.typeName(), rendered, containsString(mention));
            } else {
                assertThat(type.typeName(), rendered, not(containsString(mention)));
            }
        }
    }

    @AfterClass
    public static void renderDocs() throws IOException {
        // Gradle sets generateDocs to write or assert. Without it, do not touch the snippet.
        if (System.getProperty("generateDocs") == null) {
            return;
        }
        new DedupUnsupportedTypesDocsSupport().renderDocs();
    }

    /**
     * A type {@code DEDUP} rejects: not groupable, and a column the command can actually see.
     */
    static boolean rejectedByDedup(DataType type) {
        return type.isGroupable() == false && type.widenSmallNumeric() == type && NOT_A_DEDUP_COLUMN.contains(type) == false;
    }

    static String renderSnippet() {
        List<String> names = new ArrayList<>();
        for (DataType type : DataType.values()) {
            if (rejectedByDedup(type)) {
                names.add(type.typeName());
            }
        }
        names.sort(null);
        StringBuilder builder = new StringBuilder();
        builder.append("% This is generated by ESQL's ")
            .append(DedupUnsupportedTypesDocsTests.class.getSimpleName())
            .append(". Do not edit it. See docs/reference/query-languages/esql/README.md for how to regenerate it.\n\n");
        builder.append("`DEDUP` cannot be used when any column in scope has one of the following types: ")
            .append(englishList(names))
            .append(". Attempting to do so results in a validation error. ")
            .append("Use `KEEP` or `DROP` before `DEDUP` to remove such columns.\n");
        return builder.toString();
    }

    private static String englishList(List<String> names) {
        StringBuilder builder = new StringBuilder();
        for (int i = 0; i < names.size(); i++) {
            if (i > 0) {
                builder.append(i == names.size() - 1 ? ", or " : ", ");
            }
            builder.append('`').append(names.get(i)).append('`');
        }
        return builder.toString();
    }

    /**
     * Writes the snippet through the generateDocs callbacks.
     */
    public static class DedupUnsupportedTypesDocsSupport extends DocsV3Support {
        private static final Logger logger = LogManager.getLogger(DedupUnsupportedTypesDocsSupport.class);

        public DedupUnsupportedTypesDocsSupport() {
            super("syntax", "dedup-unsupported-types", DedupUnsupportedTypesDocsTests.class, Set::of, callbacksFromSystemProperty());
        }

        @Override
        protected void renderDocs() throws IOException {
            String rendered = renderSnippet();
            logger.info("Writing DEDUP unsupported types snippet:\n{}", rendered);
            Path dir = PathUtils.get(System.getProperty("java.io.tmpdir")).resolve("esql").resolve("_snippets").resolve(category);
            callbacks.write(dir, name, "md", rendered, false);
        }
    }
}

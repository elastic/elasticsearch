/** Frozen owner-supplied Ki R2 histories; no expected result is generated by this matcher. */
public class SequenceRememberedGoldenTests extends ESTestCase {
    private static final SequenceLatestValidConfig.ValueDemand VALUE = new SequenceLatestValidConfig.ValueDemand(
        new ReferenceAttribute(Source.EMPTY, null, "value", DataType.INTEGER)
    );

    /** The remembered-chain rule retains every pinned member, admission/drop counter and post-list per-key peak. */
    public void testAllFiftyPinnedHistories() throws IOException {
        List<?> cases = cases();
        assertEquals(50, cases.size());
        for (Object value : cases) {
            Map<?, ?> fixture = map(value);
            try (Harness h = new Harness(fixture, false)) {
                h.run(fixture);
                assertEquals(fixture.get("id").toString(), map(fixture.get("expected")).get("rule"), h.matches);
                Map<?, ?> counters = map(map(fixture.get("counters")).get("rule"));
                assertEquals(fixture.get("id") + "/drops", number(counters.get("dropped_at_limit")), h.matcher.boundDrops());
                var admission = h.matcher.admissionCounters();
                assertEquals(
                    fixture.get("id") + "/not-kept",
                    number(counters.get("not_kept_no_valid_chain")),
                    admission.candidatesNotKept()
                );
                assertEquals(fixture.get("id") + "/peak", number(counters.get("peak_rows_kept")), admission.peakCandidatesKeptPerKey());
                assertEquals(
                    fixture.get("id") + "/arrival-abandoned",
                    number(counters.get("arrival_searches_abandoned")),
                    admission.arrivalSearchesAbandoned()
                );
                assertEquals(
                    fixture.get("id") + "/all-abandoned",
                    number(counters.get("arrival_searches_abandoned")) + number(counters.get("final_searches_abandoned")),
                    h.matcher.latestValidCounters().searchesAbandonedAtWorkLimit()
                );
                if (h.stages <= 4) {
                    assertTrue(admission.peakCandidatesKeptPerKey() <= (long) h.bound * h.stages * (h.stages - 1) / 2);
                }
                logger.info(
                    "Ki R2 case [{}] matches [{}] existing [{}] admission [{}]",
                    fixture.get("id"),
                    h.matches,
                    h.matcher.latestValidCounters(),
                    admission
                );
            }
        }
    }

    /** G47 is matcher-only: its legacy arrival-only label actually disables both work limits. */
    public void testG47BothWorkLimitsDisabled() throws IOException {
        Map<?, ?> fixture = cases().stream()
            .map(SequenceRememberedGoldenTests::map)
            .filter(c -> c.get("id").toString().startsWith("G47-"))
            .findFirst()
            .orElseThrow();
        try (Harness h = new Harness(fixture, true)) {
            h.run(fixture);
            assertEquals(map(fixture.get("expected")).get("rule_without_work_limit"), h.matches);
            assertEquals(map(fixture.get("expected")).get("rule_without_arrival_limit"), h.matches);
            assertEquals(132168L, h.lastFinalSteps);
            assertEquals(0L, h.matcher.latestValidCounters().searchesAbandonedAtWorkLimit());
        }
    }

    private List<?> cases() throws IOException {
        try (
            var stream = getClass().getResourceAsStream("ki-r2-golden.json");
            var parser = JsonXContent.jsonXContent.createParser(XContentParserConfiguration.EMPTY, stream)
        ) {
            return list(parser.map().get("cases"));
        }
    }

    private static Map<?, ?> map(Object value) {
        if (value instanceof Map<?, ?> result) {
            return result;
        }
        throw new IllegalArgumentException("expected map: " + value);
    }

    private static List<?> list(Object value) {
        if (value instanceof List<?> result) {
            return result;
        }
        throw new IllegalArgumentException("expected list: " + value);
    }

    private static long number(Object value) {
        return ((Number) value).longValue();
    }

    private static Object cell(SequenceLatestValidConfig.SelectedValues values, int stage) {
        Block block = values.block(stage, 0);
        if (block.isNull(0)) {
            return null;
        }
        IntBlock ints = (IntBlock) block;
        if (block.getValueCount(0) == 1) {
            return ints.getInt(block.getFirstValueIndex(0));
        }
        List<Integer> result = new ArrayList<>();
        for (int index = block.getFirstValueIndex(0); index < block.getFirstValueIndex(0) + block.getValueCount(0); index++) {
            result.add(ints.getInt(index));
        }
        return result;
    }

    private static Boolean comparison(String op, Object a, Object b) {
        if (a instanceof Number left && b instanceof Number right) {
            return switch (op) {
                case "eq" -> left.longValue() == right.longValue();
                case "ne" -> left.longValue() != right.longValue();
                case "gt" -> left.longValue() > right.longValue();
                case "ge" -> left.longValue() >= right.longValue();
                default -> throw new IllegalArgumentException(op);
            };
        }
        return null;
    }

    private static Boolean evaluate(List<?> spec, int owner, SequenceLatestValidConfig.SelectedValues values) {
        String op = spec.getFirst().toString();
        Object own = cell(values, owner);
        if (op.equals("and") || op.equals("or")) {
            Boolean result = op.equals("and");
            for (Object part : spec.subList(1, spec.size())) {
                Boolean next = evaluate(list(part), owner, values);
                if (op.equals("and")) {
                    result = Boolean.FALSE.equals(result) || Boolean.FALSE.equals(next) ? Boolean.FALSE
                        : result == null || next == null ? null
                        : Boolean.TRUE;
                } else {
                    result = Boolean.TRUE.equals(result) || Boolean.TRUE.equals(next) ? Boolean.TRUE
                        : result == null || next == null ? null
                        : Boolean.FALSE;
                }
            }
            return result;
        }
        if (op.equals("own_eq_const") || op.equals("own_gt_const")) {
            return comparison(op.equals("own_eq_const") ? "eq" : "gt", own, spec.get(1));
        }
        Object first = cell(values, Math.toIntExact(number(spec.get(1))) - 1);
        return switch (op) {
            case "eq", "ne", "gt", "ge" -> comparison(op, own, first);
            case "is_null_ref" -> first == null;
            case "mv_contains_ref" -> own instanceof Number
                ? first instanceof List<?> items ? items.contains(own) : own.equals(first)
                : null;
            case "ref_eq_const" -> comparison("eq", first, spec.get(2));
            case "ne_refs" -> comparison("ne", first, cell(values, Math.toIntExact(number(spec.get(2))) - 1));
            case "eq_sum" -> {
                Object second = cell(values, Math.toIntExact(number(spec.get(2))) - 1);
                yield comparison("eq", own, first instanceof Number a && second instanceof Number b ? a.longValue() + b.longValue() : null);
            }
            default -> throw new IllegalArgumentException(op);
        };
    }

    private static void references(List<?> spec, TreeSet<Integer> refs) {
        String op = spec.getFirst().toString();
        switch (op) {
            case "and", "or" -> spec.subList(1, spec.size()).forEach(part -> references(list(part), refs));
            case "own_eq_const", "own_gt_const" -> {
            }
            case "eq", "ne", "gt", "ge", "is_null_ref", "mv_contains_ref", "ref_eq_const" -> refs.add(
                Math.toIntExact(number(spec.get(1))) - 1
            );
            case "eq_sum", "ne_refs" -> {
                refs.add(Math.toIntExact(number(spec.get(1))) - 1);
                refs.add(Math.toIntExact(number(spec.get(2))) - 1);
            }
            default -> throw new IllegalArgumentException(op);
        }
    }

    private static List<SequenceLatestValidConfig.PredicateGroup> groups(Map<?, ?> fixture) {
        List<SequenceLatestValidConfig.PredicateGroup> result = new ArrayList<>();
        for (var entry : map(fixture.get("conditions")).entrySet()) {
            int owner = Integer.parseInt(entry.getKey().toString()) - 1;
            Map<Integer, List<List<?>>> grouped = new LinkedHashMap<>();
            Map<Integer, TreeSet<Integer>> allRefs = new LinkedHashMap<>();
            for (Object part : list(entry.getValue())) {
                List<?> spec = list(part);
                TreeSet<Integer> refs = new TreeSet<>();
                references(spec, refs);
                if (refs.isEmpty()) {
                    refs.add(owner - 1);
                }
                int minimum = refs.first();
                grouped.computeIfAbsent(minimum, ignored -> new ArrayList<>()).add(spec);
                allRefs.computeIfAbsent(minimum, ignored -> new TreeSet<>()).addAll(refs);
            }
            for (var group : grouped.entrySet()) {
                result.add(new SequenceLatestValidConfig.PredicateGroup(owner, List.copyOf(allRefs.get(group.getKey())), values -> {
                    // Every conjunct runs before conversion to the group's WHERE truth value.
                    boolean passed = true;
                    for (List<?> spec : group.getValue()) {
                        passed &= Boolean.TRUE.equals(evaluate(spec, owner, values));
                    }
                    return passed;
                }));
            }
        }
        return result;
    }

    private static final class Harness implements Releasable {
        private final HierarchyCircuitBreakerService service = new HierarchyCircuitBreakerService(
            CircuitBreakerMetrics.NOOP,
            Settings.builder().put("indices.breaker.request.limit", "64mb").build(),
            List.of(),
            new ClusterSettings(Settings.EMPTY, ClusterSettings.BUILT_IN_CLUSTER_SETTINGS)
        );
        private final CircuitBreaker breaker = service.getBreaker(CircuitBreaker.REQUEST);
        private final BlockFactory blocks = BlockFactory.builder(BigArrays.NON_RECYCLING_INSTANCE).breaker(breaker).build();
        private final SequenceLatestValidConfig config;
        private final SequenceLatestValidMatcher matcher;
        private final int stages;
        private final int bound;
        private final List<List<String>> matches = new ArrayList<>();
        private long lastFinalSteps;

        private Harness(Map<?, ?> fixture, boolean freeWork) {
            stages = Math.toIntExact(number(fixture.get("stages")));
            bound = Math.toIntExact(number(fixture.get("limit")));
            var demands = java.util.Collections.nCopies(stages, List.of(VALUE));
            long finalLimit = freeWork || fixture.get("final_step_limit") == null
                ? Long.MAX_VALUE
                : number(fixture.get("final_step_limit"));
            long arrivalLimit = freeWork || fixture.get("arrival_step_limit") == null
                ? Long.MAX_VALUE
                : number(fixture.get("arrival_step_limit"));
            config = SequenceLatestValidConfig.boundedForTests(bound, finalLimit, demands, groups(fixture))
                .withArrivalLimitForTests(arrivalLimit);
            long[] gaps = new long[stages];
            for (var gap : map(fixture.get("step_limits")).entrySet()) {
                gaps[Integer.parseInt(gap.getKey().toString()) - 1] = number(gap.getValue()) * 1_000_000;
            }
            long window = fixture.get("window") == null ? 1_000_000_000L : number(fixture.get("window"));
            matcher = new SequenceLatestValidMatcher(
                stages,
                TimeValue.timeValueMillis(window),
                breaker,
                () -> false,
                BytesRef::compareTo,
                gaps,
                config
            );
        }

        private void run(Map<?, ?> fixture) {
            Map<String, Integer> events = new LinkedHashMap<>();
            List<Map<?, ?>> rows = new ArrayList<>();
            for (Object value : list(fixture.get("rows"))) {
                Map<?, ?> row = map(value);
                events.computeIfAbsent(row.get("event").toString(), ignored -> events.size());
                rows.add(row);
            }
            rows.sort(
                Comparator.comparingInt((Map<?, ?> row) -> events.get(row.get("event").toString()))
                    .thenComparing((a, b) -> Long.compare(number(b.get("stage")), number(a.get("stage"))))
                    .thenComparing(row -> row.get("key") == null ? "k" : row.get("key").toString())
                    .thenComparingLong(row -> number(row.get("row")))
            );
            for (Map<?, ?> row : rows) {
                int stage = Math.toIntExact(number(row.get("stage"))) - 1;
                long before = matcher.latestValidCounters().searchSteps();
                try (
                    SequenceMatch match = matcher.match(
                        stage,
                        new BytesRef(row.get("key") == null ? "k" : row.get("key").toString()),
                        new SequenceOrdinal(number(row.get("time")), 0, events.get(row.get("event").toString())),
                        new BytesRef(row.get("label").toString()),
                        values(stage, row.get("value"))
                    )
                ) {
                    if (match != null) {
                        matches.add(match.handles().stream().map(BytesRef::utf8ToString).toList());
                    }
                }
                if (stage == stages - 1) {
                    lastFinalSteps = matcher.latestValidCounters().searchSteps() - before;
                }
            }
        }

        private SequenceCandidateValues values(int stage, Object value) {
            try (var builder = blocks.newIntBlockBuilder(1)) {
                if (value == null) {
                    builder.appendNull();
                } else if (value instanceof Number numeric) {
                    builder.appendInt(numeric.intValue());
                } else {
                    builder.beginPositionEntry();
                    for (Object item : list(value)) {
                        builder.appendInt(Math.toIntExact(number(item)));
                    }
                    builder.endPositionEntry();
                }
                try (Page page = new Page(builder.build())) {
                    return SequenceCandidateValues.copyRow(page, 0, config.mandatoryDemands().get(stage), new int[] { 0 }, blocks, breaker);
                }
            }
        }

        @Override
        public void close() {
            matcher.close();
            assertEquals(0L, breaker.getUsed());
        }
    }
}

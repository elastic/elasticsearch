package org.elasticsearch.xpack.esql.expression.function.aggregate;

import org.elasticsearch.common.Strings;
import org.elasticsearch.core.PathUtils;
import org.elasticsearch.test.ESTestCase;
import org.elasticsearch.xcontent.XContentBuilder;
import org.elasticsearch.xcontent.json.JsonXContent;
import org.elasticsearch.xpack.esql.core.type.DataType;
import org.elasticsearch.xpack.esql.expression.function.DocsV3Support;

import java.nio.file.Path;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;

import static org.elasticsearch.xpack.esql.core.type.DataType.AGGREGATE_METRIC_DOUBLE;
import static org.elasticsearch.xpack.esql.core.type.DataType.BOOLEAN;
import static org.elasticsearch.xpack.esql.core.type.DataType.DATETIME;
import static org.elasticsearch.xpack.esql.core.type.DataType.DOUBLE;
import static org.elasticsearch.xpack.esql.core.type.DataType.INTEGER;
import static org.elasticsearch.xpack.esql.core.type.DataType.KEYWORD;
import static org.elasticsearch.xpack.esql.core.type.DataType.LONG;
import static org.hamcrest.Matchers.contains;
import static org.hamcrest.Matchers.hasItems;

/**
 * Generates the Kibana definition file describing the implicit union casts applied to
 * {@code aggregate_metric_double} conflicts: when a field is mapped as {@code aggregate_metric_double}
 * in one index and a plain numeric in another (the shape raw-versus-downsampled indices produce),
 * the {@code ImplicitCastAggregateMetricDoubles} analyzer rule implicitly reconciles the legs under
 * {@code avg}, {@code sum}, {@code min}, {@code max} and {@code count} (and in binary comparisons),
 * so the query runs even though field discovery reports the column as {@code unsupported}.
 * Kibana uses this file to tell a resolvable conflict from a fatal one instead of guessing
 * from {@code suggested_cast}.
 * <p>
 * Run with:
 * <pre>
 * ./gradlew :x-pack:plugin:esql:test --tests "ImplicitUnionCastKibanaDefinitionTests"
 * </pre>
 */
public class ImplicitUnionCastKibanaDefinitionTests extends ESTestCase {

    /**
     * The aggregate functions whose implicit union cast this file describes: the contract named by the
     * {@code ImplicitCastAggregateMetricDoubles} rule (min, max, sum, count and avg).
     */
    static List<String> implicitlyCastingFunctions() {
        return List.of("avg", "count", "max", "min", "sum");
    }

    /**
     * The conflict-leg types the rule reconciles, mirroring its {@code canBeCast} condition: the conflict
     * must contain {@code aggregate_metric_double} and every leg must be numeric or {@code aggregate_metric_double}.
     */
    static Set<String> acceptedLegTypes() {
        Set<String> legs = new TreeSet<>();
        for (DataType dataType : DataType.values()) {
            if (dataType.isNumericOrAmd()) {
                legs.add(dataType.esNameIfPossible());
            }
        }
        return legs;
    }

    public void testAcceptedLegTypes() {
        Set<String> legs = acceptedLegTypes();
        // the conflict from the issue: raw (double) versus downsampled (aggregate_metric_double) legs
        assertThat(legs, hasItems(DOUBLE.esNameIfPossible(), AGGREGATE_METRIC_DOUBLE.esNameIfPossible()));
        assertThat(legs, hasItems(INTEGER.esNameIfPossible(), LONG.esNameIfPossible()));
        // non-numeric legs never reconcile
        for (DataType rejected : new DataType[] { KEYWORD, BOOLEAN, DATETIME }) {
            assertFalse("unexpected leg [" + rejected + "]", legs.contains(rejected.esNameIfPossible()));
        }
    }

    public void testImplicitlyCastingFunctions() {
        assertThat(implicitlyCastingFunctions(), contains("avg", "count", "max", "min", "sum"));
    }

    public void testGenerateKibanaDefinition() throws Exception {
        String rendered;
        try (XContentBuilder builder = JsonXContent.contentBuilder().prettyPrint().lfAtEnd().startObject()) {
            builder.field(
                "comment",
                "This is generated by ESQL's ImplicitUnionCastKibanaDefinitionTests. "
                    + "Do not edit it. See docs/reference/query-languages/esql/README.md for how to regenerate it."
            );
            builder.startObject("conflict");
            builder.field("contains", AGGREGATE_METRIC_DOUBLE.esNameIfPossible());
            builder.stringListField("allLegsIn", acceptedLegTypes().stream().sorted().toList());
            builder.endObject();
            builder.stringListField("functions", implicitlyCastingFunctions());
            builder.field("comparisons", true);
            rendered = Strings.toString(builder.endObject());
        }
        DocsV3Support.Callbacks callbacks = DocsV3Support.callbacksFromSystemProperty();
        Path dir = PathUtils.get(System.getProperty("java.io.tmpdir")).resolve("esql").resolve("kibana").resolve("definition");
        callbacks.write(dir, "implicit_union_casts", "json", rendered, true);
    }
}

package org.elasticsearch.xpack.esql.formatter.arrow;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import org.apache.arrow.vector.types.pojo.ArrowType;
import org.apache.arrow.vector.types.pojo.Field;
import org.elasticsearch.core.PathUtils;
import org.elasticsearch.xpack.esql.core.type.DataType;
import org.elasticsearch.xpack.esql.expression.function.DocsV3Support;

import java.io.IOException;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.Iterator;
import java.util.Map;

/** Generates the Arrow reference through the same write/assert callbacks as ES|QL function docs. */
final class ArrowDocsSupport {
    private static final ObjectMapper JACKSON = new ObjectMapper();

    private ArrowDocsSupport() {}

    static void renderDocs() throws IOException {
        if (System.getProperty("generateDocs") == null) {
            return;
        }
        var types = ArrowResponse.ESQL_FORMATTERS.keySet().stream().sorted(Comparator.comparing(DataType::outputType)).toList();
        StringBuilder reference = new StringBuilder(
            "% This is generated by ESQL's ArrowResponseTests. Do not edit it. "
                + "See docs/reference/query-languages/esql/README.md for how to regenerate it.\n\n"
        );
        reference.append("## Supported types [esql-arrow-supported-types]\n\n");
        reference.append("`value` stands for the result column name. Select a form inside each type to inspect its fields.\n\n");
        reference.append("| ES\\|QL type | Arrow type for a single value |\n| --- | --- |\n");
        for (var type : types) {
            reference.append("| `")
                .append(type.outputType())
                .append("` | `")
                .append(renderType(ArrowResponse.ESQL_FORMATTERS.get(type).arrowField("value").getType()))
                .append("` |\n");
        }
        reference.append("\n");
        for (var type : types) {
            var formatter = ArrowResponse.ESQL_FORMATTERS.get(type);
            reference.append("::::::{dropdown} ").append(type.outputType()).append("\n\n");
            if (type == DataType.NULL || type == DataType.UNSUPPORTED) {
                appendSchema(reference, ArrowResponse.arrowField(formatter, "value", false));
            } else {
                reference.append(":::::{tab-set}\n\n::::{tab-item} Single value\n\n");
                appendSchema(reference, ArrowResponse.arrowField(formatter, "value", false));
                reference.append("::::\n\n::::{tab-item} Multivalue\n\n");
                appendSchema(reference, ArrowResponse.arrowField(formatter, "value", true));
                reference.append("::::\n\n:::::\n\n");
            }
            reference.append("::::::\n\n");
        }
        reference.append("## Types without an Arrow formatter [esql-arrow-unsupported-types]\n\n");
        reference.append("Convert or remove columns of these types before requesting Arrow:\n\n");
        ArrowResponse.TO_BE_IMPLEMENTED_FORMATTERS.stream()
            .sorted(Comparator.comparing(DataType::outputType))
            .forEach(type -> reference.append("* `").append(type.outputType()).append("`\n"));
        var dir = PathUtils.get(System.getProperty("java.io.tmpdir")).resolve("esql/_snippets/syntax");
        DocsV3Support.callbacksFromSystemProperty().write(dir, "arrow-types", "md", reference.toString(), false);
    }

    private static void appendSchema(StringBuilder reference, Field field) {
        reference.append(":::{schema-tree} Arrow schema\n\n");
        appendField(reference, field, 0);
        reference.append(":::\n\n");
    }

    private static void appendField(StringBuilder reference, Field field, int depth) {
        reference.append("  ".repeat(depth))
            .append("* `")
            .append(field.getName())
            .append("` — `")
            .append(renderType(field.getType()))
            .append("` — ")
            .append(field.isNullable() ? "nullable" : "non-null")
            .append("\n\n");
        field.getMetadata()
            .entrySet()
            .stream()
            .sorted(Map.Entry.comparingByKey())
            .forEach(
                entry -> reference.append("  ".repeat(depth + 1))
                    .append("Metadata: `")
                    .append(entry.getKey())
                    .append(" = ")
                    .append(entry.getValue())
                    .append("`\n\n")
            );
        for (var child : field.getChildren()) {
            appendField(reference, child, depth + 1);
        }
    }

    /**
     * Renders an Arrow type for the reference, e.g. {@code Int(bitWidth: 32, isSigned: true)}.
     * <p>
     * {@link ArrowType#toString()} emits a bare positional list ({@code Int(32, true)}) that reads like a Java
     * constructor call, so the parameters are unnamed. Arrow's type classes carry Jackson annotations, so we
     * serialize the type to get named parameters. The serialized {@code name} property is dropped because it
     * duplicates the type id, which is used as the rendered prefix.
     */
    private static String renderType(ArrowType type) {
        JsonNode json;
        try {
            json = JACKSON.valueToTree(type);
        } catch (IllegalArgumentException e) {
            // Annotated types serialize structurally; keep the raw form for anything Jackson can't handle.
            return type.toString();
        }
        var parameters = new ArrayList<String>();
        for (Iterator<Map.Entry<String, JsonNode>> it = json.fields(); it.hasNext();) {
            Map.Entry<String, JsonNode> entry = it.next();
            if ("name".equals(entry.getKey()) == false) {
                parameters.add(entry.getKey() + ": " + renderValue(entry.getValue()));
            }
        }
        if (parameters.isEmpty()) {
            return type.getTypeID().toString();
        }
        return type.getTypeID() + "(" + String.join(", ", parameters) + ")";
    }

    private static String renderValue(JsonNode value) {
        return value.isTextual() ? value.textValue() : value.toString();
    }
}

package org.elasticsearch.xpack.stateless.commits;

import org.elasticsearch.xpack.stateless.engine.PrimaryTermAndGeneration;

import java.util.HexFormat;

import static org.elasticsearch.test.ESTestCase.randomBoolean;
import static org.elasticsearch.test.ESTestCase.randomByteArrayOfLength;
import static org.elasticsearch.test.ESTestCase.randomNonNegativeLong;
import static org.elasticsearch.xpack.stateless.commits.StatelessCompoundCommitTestUtils.randomNonZeroPositiveLong;

public class BlobFileTestUtils {

    private BlobFileTestUtils() {}

    /** @return either a {@link BccBlobFile} or a {@link MergeBlobFile} */
    public static BlobFile randomBlobFile() {
        return randomBoolean() ? randomBccBlobFile() : randomMergeBlobFile();
    }

    public static BccBlobFile randomBccBlobFile() {
        return new BccBlobFile(new PrimaryTermAndGeneration(randomNonZeroPositiveLong(), randomNonZeroPositiveLong()));
    }

    public static MergeBlobFile randomMergeBlobFile() {
        return new MergeBlobFile(
            MergeBlobFile.blobName(randomNonZeroPositiveLong(), randomMergeSegment(), randomMergeDiscriminator()),
            randomNonZeroPositiveLong()
        );
    }

    /** A segment name as generated by Lucene: a lowercase base 36 number, without the leading underscore. */
    public static String randomMergeSegment() {
        return Long.toString(randomNonNegativeLong(), Character.MAX_RADIX);
    }

    /** A discriminator as generated by the engine: 8 random bytes formatted as 16 lowercase hexadecimal characters. */
    public static String randomMergeDiscriminator() {
        return HexFormat.of().formatHex(randomByteArrayOfLength(8));
    }
}
